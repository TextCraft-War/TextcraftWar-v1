//! 系统状态：全服定时结算的进度（单行表，D32）。
//!
//! 每小时给所有人 +1 生产次数、每天 0 点清零招募数量都是**全服批处理**；
//! 进度（"结算到哪了"）存在 `系统状态` 那一行的两个时间戳里，漏跑能补算。
//!
//! 本模块是 S4 定时结算的地基：查进度、**锁行**、写回。
//! 结算的串行化点就是 [`锁定状态`] 的 `FOR UPDATE`——后台任务与并发的
//! 指令事务都抢这一行，谁先锁住谁结算，后到者等前者提交后再读新进度。

use crate::连接::{事务, 执行者};
use crate::错误;

/// `系统状态` 的那一行。`id` 恒为 1（迁移里的 `CHECK (id = 1)`）。
#[derive(Debug, Clone, Copy, PartialEq, Eq, sqlx::FromRow)]
pub struct 系统状态行 {
    /// 恒为 1。
    pub id: i16,
    /// 生产次数结算到哪一刻；`None` = 还没结算过。
    pub 上次生产结算: Option<i64>,
    /// 上次日结（招募清零）时刻；`None` = 还没日结过。
    pub 上次日结: Option<i64>,
}

/// 读全服结算进度。纯读，不需要事务。
pub async fn 查状态(于: 执行者<'_>) -> Result<系统状态行, 错误> {
    let mut 源 = 于.解析().await?;
    sqlx::query_as::<_, 系统状态行>(
        "SELECT id, 上次生产结算, 上次日结 FROM 系统状态 WHERE id = 1",
    )
    .fetch_one(源.连接())
    .await
    .map_err(|来源| 错误::数据库失败 {
        操作: "查询系统状态",
        来源,
    })
}

/// 在事务里锁定进度行（`SELECT … FOR UPDATE`），返回锁定时的进度。
///
/// 这是**定时结算的串行化点**：补算 → 写回必须在同一个事务里，
/// 且事务里不得再 await 别的外部 IO。两个结算任务并发时，后到者在这里
/// 等前者提交，再基于新进度补算，不会重复加次数。
pub async fn 锁定状态(句柄: &mut 事务) -> Result<系统状态行, 错误> {
    sqlx::query_as::<_, 系统状态行>(
        "SELECT id, 上次生产结算, 上次日结 FROM 系统状态 WHERE id = 1 FOR UPDATE",
    )
    .fetch_one(句柄.连接())
    .await
    .map_err(|来源| 错误::数据库失败 {
        操作: "锁定系统状态",
        来源,
    })
}

/// 写回进度。必须与 [`锁定状态`] 在同一个事务里，否则锁白拿。
pub async fn 写状态(句柄: &mut 事务, 行: 系统状态行) -> Result<(), 错误> {
    sqlx::query(
        "UPDATE 系统状态
            SET 上次生产结算 = $1, 上次日结 = $2
          WHERE id = 1",
    )
    .bind(行.上次生产结算)
    .bind(行.上次日结)
    .execute(句柄.连接())
    .await
    .map_err(|来源| 错误::数据库失败 {
        操作: "写回系统状态",
        来源,
    })?;

    Ok(())
}
