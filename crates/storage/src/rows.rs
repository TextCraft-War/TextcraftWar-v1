//! 数据库行类型与「行 → domain 实体」的防腐转换（data-model 第七节）。
//!
//! 规则：
//!
//! - 行类型 `#[derive(sqlx::FromRow)]`，字段名 = 列名，**只在 `storage` 内部可见**，
//!   绝不带 `Serialize`；
//! - `domain` 的实体**绝不**带 `FromRow`；
//! - 两者之间用 `TryFrom` 转换，**所有窄化校验集中在这里**：
//!   `BIGINT → u8` 这类有损转换不允许 `as`——超范围 = 数据损坏，
//!   返回 [`错误::数据损坏`]，宁可炸出错误也不静默截断。
//!
//! 查询函数不直接解裸元组：加一列只改行类型 + 转换两处，不碰每一条调用方。

use domain::实体::{
    地区Id, 时间, 权限等级, 玩家, 玩家Id, 玩家Uid, 联军Id, 联军职务
};

use crate::错误;

/// `玩家` 表的行（data-model 4.1）。
///
/// `SELECT *` 直接喂给它：列名与迁移 `11_player.sql` 一一对应，
/// 结果集里的多余列（`FromRow` 按列名取值）会被忽略——
/// `创建时间` 之类的列不在行类型里，因为 `domain::玩家` 不带它们。
#[derive(Debug, sqlx::FromRow)]
pub(crate) struct 玩家行 {
    /// 主键。
    pub id: i64,
    /// 六位秘密编号（显示为 `P…`）。
    pub uid: i32,
    /// 从事生产的人口。
    pub 工人: i64,
    /// 操作兵器的兵员。
    pub 私军: i64,
    /// 地下工厂的工人。
    pub 地下工人: i64,
    /// 暂离的工人。
    pub 休假工人: i64,
    /// 科技等级。
    pub 科技: i64,
    /// 产量乘数。
    pub 生产技术: i64,
    /// 产能上限。
    pub 厂房: i64,
    /// 地下工厂累计投入。
    pub 地下工厂投入: i64,
    /// 科技池已投入。
    pub 科技池投入: i64,
    /// 科技池容量。
    pub 科技池容量: i64,
    /// 可积攒的生产次数（`0..=8`，全服批处理推进）。
    pub 生产次数: i64,
    /// 军事行动点。
    pub 军事行动点: i64,
    /// 稳定度（可为负）。
    pub 稳定度: i64,
    /// 工资。
    pub 工资: i64,
    /// 上次签到；`NULL` = 从没签过。
    pub 上次签到时间: Option<i64>,
    /// 今日已招数量。
    pub 今日招募数量: i64,
    /// 炮击冷却锚点。
    pub 上次炮击时间: Option<i64>,
    /// 驻扎冷却锚点。
    pub 上次驻扎时间: Option<i64>,
    /// 驻扎地区（弱引用）。
    pub 驻扎地区_id: Option<i64>,
    /// 所在联军。
    pub 联军_id: Option<i64>,
    /// 职务编码（`leader` / `premier` / `officer` / `member`）。
    pub 联军职务: Option<String>,
    /// 权限等级（1–3；元首/总理为 `NULL`）。
    pub 联军权限等级: Option<i16>,
    /// 对当前联军的贡献。
    pub 联军贡献: i64,
    /// 入盟时间。
    pub 加入联军时间: Option<i64>,
    /// 出生保护截止。
    pub 出生保护至: Option<i64>,
}

impl TryFrom<玩家行> for 玩家 {
    type Error = 错误;

    fn try_from(行: 玩家行) -> Result<Self, Self::Error> {
        // 窄化校验：超范围是数据损坏，不是"取个低八位"。
        let 生产次数 = u8::try_from(行.生产次数).map_err(|_| 错误::数据损坏 {
            表: "玩家",
            列: "生产次数",
        })?;
        if 生产次数 > 8 {
            return Err(错误::数据损坏 {
                表: "玩家",
                列: "生产次数",
            });
        }

        let 职务 = 行
            .联军职务
            .map(|编码| {
                联军职务::解析(&编码).ok_or(错误::数据损坏 {
                    表: "玩家",
                    列: "联军职务",
                })
            })
            .transpose()?;

        let 等级 = 行
            .联军权限等级
            .map(|落库值| {
                权限等级::解析(落库值).ok_or(错误::数据损坏 {
                    表: "玩家",
                    列: "联军权限等级",
                })
            })
            .transpose()?;

        Ok(Self {
            id: 玩家Id(行.id),
            uid: 玩家Uid(行.uid),
            工人: 行.工人,
            私军: 行.私军,
            地下工人: 行.地下工人,
            休假工人: 行.休假工人,
            科技: 行.科技,
            生产技术: 行.生产技术,
            厂房: 行.厂房,
            地下工厂投入: 行.地下工厂投入,
            科技池投入: 行.科技池投入,
            科技池容量: 行.科技池容量,
            生产次数,
            军事行动点: 行.军事行动点,
            稳定度: 行.稳定度,
            工资: 行.工资,
            上次签到: 行.上次签到时间.map(时间),
            今日招募数量: 行.今日招募数量,
            上次炮击: 行.上次炮击时间.map(时间),
            上次驻扎: 行.上次驻扎时间.map(时间),
            驻扎地区: 行.驻扎地区_id.map(地区Id),
            联军: 行.联军_id.map(联军Id),
            联军职务: 职务,
            联军权限等级: 等级,
            联军贡献: 行.联军贡献,
            加入联军时间: 行.加入联军时间.map(时间),
            出生保护至: 行.出生保护至.map(时间),
        })
    }
}

/// `平台绑定 JOIN 玩家` 查询的行（登录路径）。
#[derive(Debug, sqlx::FromRow)]
pub(crate) struct 绑定行 {
    /// 玩家主键。
    pub 玩家_id: i64,
    /// 玩家六位编号。
    pub 编号: i32,
}

/// `地区频道绑定 JOIN 地区` 查询的行（频道定位路径）。
#[derive(Debug, sqlx::FromRow)]
pub(crate) struct 频道地区行 {
    /// 地区主键。
    pub id: i64,
    /// 地区名（公开信息；行里刻意不带 `uid`——秘密凭证只给"已经知道的人"）。
    pub 名称: String,
}

/// `库存` 表的一行；所有者两列在查询的 `WHERE` 里已定死，不必带出来。
#[derive(Debug, sqlx::FromRow)]
pub(crate) struct 库存行 {
    /// 物品编码（catalog 稳定键，如 `resource:food`）。
    pub 物品: String,
    /// 数量（DOMAIN `非负计数`，读出来只会 ≥ 0）。
    pub 数量: i64,
}

#[cfg(test)]
mod 测试 {
    use super::玩家行;
    use crate::错误;
    use domain::实体::{权限等级, 玩家, 联军职务};

    fn 合法行() -> 玩家行 {
        玩家行 {
            id: 7,
            uid: 123_456,
            工人: 10,
            私军: 2,
            地下工人: 0,
            休假工人: 1,
            科技: 3,
            生产技术: 1,
            厂房: 0,
            地下工厂投入: 0,
            科技池投入: 0,
            科技池容量: 0,
            生产次数: 5,
            军事行动点: 0,
            稳定度: 50,
            工资: 0,
            上次签到时间: Some(1_700_000_000),
            今日招募数量: 0,
            上次炮击时间: None,
            上次驻扎时间: None,
            驻扎地区_id: Some(3),
            联军_id: Some(9),
            联军职务: Some("leader".to_owned()),
            联军权限等级: None,
            联军贡献: 120,
            加入联军时间: Some(1_700_000_100),
            出生保护至: None,
        }
    }

    #[test]
    fn 全字段行能转成领域玩家() {
        let 玩家实体 = 玩家::try_from(合法行()).expect("合法行必须能转换");

        assert_eq!(玩家实体.id.0, 7);
        assert_eq!(玩家实体.uid.0, 123_456);
        assert_eq!(玩家实体.生产次数, 5);
        assert_eq!(玩家实体.联军职务, Some(联军职务::元首));
        assert_eq!(玩家实体.联军权限等级, None);
        assert_eq!(玩家实体.上次签到.map(|时间| 时间.0), Some(1_700_000_000));
        assert_eq!(玩家实体.驻扎地区.map(|地区| 地区.0), Some(3));
        assert_eq!(玩家实体.总人口(), 13);
    }

    #[test]
    fn 生产次数超出窄化范围判数据损坏() {
        let mut 行 = 合法行();
        行.生产次数 = 256;

        let 结果 = 玩家::try_from(行);
        assert!(
            matches!(
                结果,
                Err(错误::数据损坏 {
                    表: "玩家",
                    列: "生产次数"
                })
            ),
            "实际：{结果:?}"
        );
    }

    #[test]
    fn 生产次数超过规则上界判数据损坏() {
        let mut 行 = 合法行();
        行.生产次数 = 9;

        assert!(matches!(玩家::try_from(行), Err(错误::数据损坏 { .. })));
    }

    #[test]
    fn 职务编码不认识判数据损坏() {
        let mut 行 = 合法行();
        行.联军职务 = Some("emperor".to_owned());

        assert!(matches!(玩家::try_from(行), Err(错误::数据损坏 { .. })));
    }

    #[test]
    fn 等级超范围判数据损坏() {
        let mut 行 = 合法行();
        行.联军权限等级 = Some(4);

        assert!(matches!(玩家::try_from(行), Err(错误::数据损坏 { .. })));
    }

    #[test]
    fn 干部必须带等级的搭配由转换放行由数据库兜底() {
        // 行转换不做"职务与等级搭配"的跨列校验：那是 DB CHECK（联军职务与等级一致）
        // 与 domain 规则的事，防腐层只管单列的类型与词表。
        let mut 行 = 合法行();
        行.联军职务 = Some("member".to_owned());
        行.联军权限等级 = Some(2);

        let 玩家实体 = 玩家::try_from(行).expect("干部 + 2 级应能转换");
        assert_eq!(玩家实体.联军权限等级, Some(权限等级::二级));
    }
}
