-- 联军资本增量：每天一行，成员生产利润的合计（GDP 口径）。
--
-- v2 存了三列滚动值（当天 / 三天 / 七天）加一个 JSON 历史数组。这里只存**事实**：
-- 每天日结一行，三天、七天就是窗口内的 SUM。改成窗口聚合之后：
--   1. 没有"三列之间对不上"的可能；
--   2. 历史可以任意回溯，不用为了算七天而保留一个长度不受控的数组；
--   3. 每天每联军一行，主键天然幂等——日结重跑不会写出两行。
--
-- 口径注意：这里记的是**利润**（生产产出 − 工资），不是税收。税率只决定利润里
-- 多少进联军仓库，不影响这一行的数字——否则"GDP"会随着税率调整跳变。
--
-- 日界按 UTC+8（全服统一，见 docs/server/design.md 第五节），`日结时间` 存**那一刻的 Unix 秒**，
-- 不用 DATE：DATE 会把"几点算今天"这个决定藏进列类型里。

CREATE TABLE 联军资本增量 (
    联军_id BIGINT NOT NULL,
    日结时间 时间戳,
    资本增量 非负计数,

    PRIMARY KEY (联军_id, 日结时间)
);

COMMENT ON TABLE 联军资本增量 IS '联军资本增量的日结历史：一天一行，三天/七天增量由窗口 SUM 算出';
COMMENT ON COLUMN 联军资本增量.联军_id IS '逻辑引用 联军.id';
COMMENT ON COLUMN 联军资本增量.日结时间 IS '这一行结算的是哪一天的日界（UTC+8 零点的 Unix 秒）；主键的一部分，重跑同一天会冲突';
COMMENT ON COLUMN 联军资本增量.资本增量 IS '那一天成员生产利润的合计（生活资料计）；与税率无关——税只决定利润里多少进联军仓库';
