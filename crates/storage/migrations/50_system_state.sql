-- 系统状态：单行表，只放"全服定时结算推进到哪了"。
--
-- 为什么要这张表：每小时给所有人 +1 生产次数、每天 0 点清零今日招募数量，
-- 都是全服批处理。进程在结算点没跑（部署、崩溃、机器重启）就会漏一次——
-- 漏一次，玩家少攒一次生产次数，或者一整天不能招募。
--
-- 所以不存"每个玩家的结算锚点"（那是 D31 一开始的思路，已废弃），
-- 只存全服的两个进度；启动时和每次 tick 都能一次性补算：
--   UPDATE 玩家 SET 生产次数 = LEAST(8, 生产次数 + 漏掉的小时数)

CREATE TABLE 系统状态 (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    上次生产结算 可空时间戳,
    上次日结 可空时间戳
);

COMMENT ON TABLE 系统状态 IS '单行表：全服定时结算的进度。id 恒为 1';
COMMENT ON COLUMN 系统状态.上次生产结算 IS '生产次数结算到哪一刻；NULL = 还没结算过。启动时按 (now - 它) / 1 小时 一次性补算';
COMMENT ON COLUMN 系统状态.上次日结 IS '上次清零招募数量的时刻；跨天就再清零一次';

