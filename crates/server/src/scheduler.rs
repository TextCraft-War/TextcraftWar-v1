//! 后台调度器：定时结算的心跳与**漏跑补算**（D32，S4 第一块）。
//!
//! 形状（`crates/server/docs/impl.md` 第五节）：**每 60 秒检查一次**
//! 全服结算进度，不"睡到整点"——启动时间不整，睡到整点会错位。
//! 没活干的轮次只做一次单行表纯读（D46）；该补算才：
//! `开事务 → 锁定状态 → 按时间差补算 → 写状态 → 提交`
//! （串行化点见 `crates/storage/docs/impl.md` 2.6，`FOR UPDATE` 行锁——
//! 两个结算并发时后到者等前者提交，**基于锁定后的新进度重算**，不会重复加次数）。
//!
//! [`巡检`] 是 `pub` 的：集成测试直接驱动一轮，不必等 60 秒心跳；
//! 进程启动后的第一个 tick 立即触发，"启动先补算"天然就是它的第一轮。
//!
//! 三件事（一条 SQL 覆盖全服，impl.md 第五节）：
//! 生产次数 +1（每小时，上限 `玩家::生产次数上限`）、今日招募清零（每天 0 点）、
//! 联军日结（历史落一行 + 当日累计清零）。失败只记日志不阻塞消息处理，下一轮会补。

use std::time::Duration;

use domain::实体::玩家;
use tokio::time::MissedTickBehavior;

use crate::时钟;

/// 巡检周期：60 秒。
const 检查周期: Duration = Duration::from_secs(60);

/// 全服以 UTC+8 为"几点算今天"（D32）。日界的时区偏移写死成常量，不散落。
const 日界时区偏移秒: i64 = 8 * 3_600;

/// 一天的秒数。
const 一天秒: i64 = 86_400;

/// 启动后台调度任务，返回任务句柄（将来做优雅停机时用它收尾）。
///
/// 第一个 tick **立即**触发（`tokio::time::interval` 的语义）：
/// 进程重启后的第一次巡检天然就是"启动先补算"的入口。
pub fn 启动调度器(池: storage::连接池) -> tokio::task::JoinHandle<()> {
    tokio::spawn(async move {
        let mut 心跳 = tokio::time::interval(检查周期);
        // 巡检偶尔慢过 60 秒时不补帧：一次巡检一次检查，堆积没有意义。
        心跳.set_missed_tick_behavior(MissedTickBehavior::Skip);

        tracing::info!(周期秒 = 检查周期.as_secs(), "调度器已启动");

        loop {
            心跳.tick().await;

            if let Err(失败) = 巡检(&池).await {
                // 批处理失败只记日志、不阻塞消息处理，下一轮会补（impl.md 第五节）。
                tracing::warn!(%失败, "调度巡检失败，下一轮重试");
            }
        }
    })
}

/// 跑一轮巡检：先纯读进度（不开事务），没活干就到此为止；
/// 该补算才开事务去 `结算`（私有，见下方实现）。
///
/// `pub` 是给集成测试的：真库测试直接驱动一轮补算并断言结果，
/// 不必真等心跳（生产代码只有 [`启动调度器`] 调它）。
pub async fn 巡检(池: &storage::连接池) -> Result<(), storage::错误> {
    let 现在 = 时钟::现在();
    let 进度 = storage::查状态(storage::执行者::池(池)).await?;

    let 生产小时 = 补算::待补生产小时(进度.上次生产结算, 现在);
    let 日结 = 补算::需要日结(进度.上次日结, 现在);
    if 生产小时 == 0 && !日结 {
        tracing::debug!(上次生产结算 = ?进度.上次生产结算, 上次日结 = ?进度.上次日结, "调度巡检：无待补算");
        return Ok(());
    }

    let 报告 = 结算(池, 现在).await?;
    tracing::info!(
        生产小时 = 报告.生产小时,
        生产行数 = 报告.生产行数,
        日结 = 报告.日结了,
        "定时结算完成"
    );

    Ok(())
}

/// 一轮补算的摘要，进日志。
struct 结算报告 {
    /// 补了几个生产小时（0 = 只有日结要做）。
    生产小时: i64,
    /// 生产次数被推进的玩家行数（已到上限的行不重写）。
    生产行数: u64,
    /// 本轮是否做了日结。
    日结了: bool,
}

/// 结算本体：**恰好一个事务**，成功提交、失败回滚。
///
/// 锁定进度行（串行化点）之后要**基于锁定值重算**——预检到开锁之间，
/// 另一个结算可能已经把活干完了；这时本轮自然算出"没活"，提交空转即走。
async fn 结算(池: &storage::连接池, 现在: i64) -> Result<结算报告, storage::错误> {
    let mut 句柄 = storage::开事务(池).await?;
    let 结果 = 结算于(&mut 句柄, 现在).await;

    match 结果 {
        Ok(报告) => {
            storage::提交(句柄).await?;
            Ok(报告)
        },
        Err(失败) => {
            if let Err(回滚错误) = storage::回滚(句柄).await {
                tracing::warn!(%回滚错误, "结算事务回滚失败");
            }
            Err(失败)
        },
    }
}

/// 事务内的结算步骤。**不得在这里 await 任何数据库之外的 IO**。
async fn 结算于(
    句柄: &mut storage::事务, 现在: i64
) -> Result<结算报告, storage::错误> {
    let 进度 = storage::锁定状态(句柄).await?;

    // 生产次数：整小时数一步到位，上限以内才推进。
    let 生产小时 = 补算::待补生产小时(进度.上次生产结算, 现在);
    let 生产行数 = if 生产小时 > 0 {
        storage::结算生产次数(句柄, 生产小时).await?
    } else {
        0
    };

    // 日结：先落历史再清累计，两步同事务（storage::日结联军资本 可重入）。
    let 日结了 = 补算::需要日结(进度.上次日结, 现在);
    if 日结了 {
        storage::清零今日招募(句柄).await?;
        storage::日结联军资本(句柄, 补算::待结日界(现在)).await?;
    }

    // 写回锚点：生产锚点只推进整数个周期（余下的分钟不丢）；
    // 没锚点（从没结算过）就从本轮起算。日结锚点 = 被结算那天的 0 点。
    let 新锚点 = 补算::新生产锚点(进度.上次生产结算, 生产小时, 现在);
    storage::写状态(
        句柄,
        storage::系统状态行 {
            id: 进度.id,
            上次生产结算: Some(新锚点),
            上次日结: if 日结了 {
                Some(补算::待结日界(现在))
            } else {
                进度.上次日结
            },
        },
    )
    .await?;

    Ok(结算报告 {
        生产小时,
        生产行数,
        日结了,
    })
}

/// 补算的**纯计算**：时间差怎么折成小时、日界怎么定。
///
/// 不碰库、不碰时钟——[`crate::时钟`] 与事务都在外面，单测直接覆盖。
mod 补算 {
    use super::{一天秒, 日界时区偏移秒, 玩家};

    /// 还欠几个生产小时：**整除不进位**——余下的分钟留在锚点里，不丢。
    /// 锚点未设（`None`，从没结算过）= 0：从下一轮起算，不凭空送一个整点。
    pub(super) fn 待补生产小时(锚点: Option<i64>, 现在: i64) -> i64 {
        锚点.map_or(0, |上次| {
            现在.saturating_sub(上次) / 玩家::生产结算周期秒
        })
    }

    /// 新的生产锚点：老锚点只推进补掉的整周期数；未设 = 从现在起算。
    pub(super) fn 新生产锚点(锚点: Option<i64>, 补了小时: i64, 现在: i64) -> i64 {
        锚点.map_or(现在, |上次| {
            上次.saturating_add(补了小时.saturating_mul(玩家::生产结算周期秒))
        })
    }

    /// 时刻落在 UTC+8 的第几个自然日（自 epoch 起算）。
    const fn 日序(时刻: i64) -> i64 {
        时刻.saturating_add(日界时区偏移秒).div_euclid(一天秒)
    }

    /// 某自然日的 0 点（UTC+8）Unix 秒。
    const fn 日界(日序值: i64) -> i64 {
        日序值.saturating_mul(一天秒).saturating_sub(日界时区偏移秒)
    }

    /// 最近一个**已结束**的自然日还没日结吗。日结的永远是"昨天"：
    /// 上次锚点只要早于昨天 0 点就还欠一次。未设（`None`）= 从没日结过，需要。
    pub(super) fn 需要日结(上次: Option<i64>, 现在: i64) -> bool {
        上次.is_none_or(|时刻| 日序(时刻) < 日序(现在).saturating_sub(1))
    }

    /// 待结那天的 0 点：正常情况下是"昨天 0 点"。
    /// 漏跑好几天时多出来的天数没法按天拆回去，只并入这一行（impl.md 第五节）。
    pub(super) const fn 待结日界(现在: i64) -> i64 {
        日界(日序(现在).saturating_sub(1))
    }
}

#[cfg(test)]
mod 测试 {
    use super::补算::{待结日界, 待补生产小时, 新生产锚点, 需要日结};

    /// 固定时刻（2027-01-15 附近），纯计算不碰真实时钟。
    const 现在: i64 = 1_799_712_000;

    #[test]
    fn 待补小时_整除不进位() {
        // 差两小时多一点：只补 2，余下的秒留在锚点里。
        assert_eq!(待补生产小时(Some(现在.saturating_sub(7205)), 现在), 2);
        assert_eq!(待补生产小时(Some(现在.saturating_sub(3600)), 现在), 1);
        assert_eq!(待补生产小时(Some(现在.saturating_sub(3599)), 现在), 0);
        // 从没结算过：不凭空送整点。
        assert_eq!(待补生产小时(None, 现在), 0);
    }

    #[test]
    fn 新锚点_只推进整周期_余数保留() {
        assert_eq!(
            新生产锚点(Some(现在.saturating_sub(7205)), 2, 现在),
            现在.saturating_sub(5)
        );
        assert_eq!(新生产锚点(None, 0, 现在), 现在);
    }

    #[test]
    fn 日结_昨天没结过才算欠() {
        let 昨天 = 待结日界(现在);
        assert!(需要日结(None, 现在), "从没日结过");
        assert!(!需要日结(Some(昨天), 现在), "昨天结过了");
        assert!(
            需要日结(Some(昨天.saturating_sub(86_400)), 现在),
            "漏了一天"
        );
        assert!(
            !需要日结(Some(昨天.saturating_add(86_400)), 现在),
            "锚点在未来的情形不该出现，但语义上不算欠"
        );
    }

    #[test]
    fn 日界_按_utc_加八对齐() {
        // 1_767_225_600 = 2026-01-01 00:00 UTC = UTC+8 的 08:00。
        // 它所在自然日的 0 点 = 2025-12-31 16:00 UTC = 1_767_196_800；
        // 待结的"昨天"再往前一天：1_767_110_400。
        assert_eq!(待结日界(1_767_225_600), 1_767_110_400);
    }
}
