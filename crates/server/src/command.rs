//! 把玩家原话解析成指令。
//!
//! 规则（v1，见 `crates/server/docs/design.md` 4.1）：
//!
//! 1. 去首尾空白，**剥掉句末标点**（兼容原版 `签到。` 的习惯，但不强制）；
//! 2. 按空白切分，第一段是指令名，其余是参数；
//! 3. 指令名**精确匹配**，不做前缀匹配（否则 `生产` 和 `生产次数` 会打架）。
//!
//! 解析只认词，不碰数据库、不判权限：`注册` 能不能成功是下一层的事。

/// 一条已识别的指令。
///
/// 现在只有一个变体，看起来像凑数——但它存在的意义是**把"玩家原话"和
/// "服务器认识的动作"隔开**：路由表 `match` 的是这个枚举，
/// 而不是字符串。加指令时改这里，加参数时给变体挂字段。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum 指令 {
    /// `注册`
    注册,
    /// 认不出（保留第一个词，供日志与提示）。
    未知 {
        /// 指令名那个词；空消息时是空串。
        原文: String,
    },
}

/// 句末允许被剥掉的标点。
const 句末标点: [char; 4] = ['。', '.', '！', '!'];

/// 解析一条玩家原话。
pub(crate) fn 解析(原文: &str) -> 指令 {
    let 规整 = 原文.trim().trim_end_matches(句末标点);

    match 规整.split_whitespace().next() {
        Some("注册") => 指令::注册,
        Some(词) => 指令::未知 {
            原文: 词.to_owned(),
        },
        None => 指令::未知 {
            原文: String::new(),
        },
    }
}

#[cfg(test)]
mod 测试 {
    use super::{指令, 解析};

    #[test]
    fn 注册能被认出来() {
        assert_eq!(解析("注册"), 指令::注册);
    }

    #[test]
    fn 首尾空白与换行不影响识别() {
        assert_eq!(解析("  注册  "), 指令::注册);
        assert_eq!(解析("\n注册\n"), 指令::注册);
    }

    #[test]
    fn 句末标点会被剥掉() {
        // 原版玩家习惯每句都带句号，v1 不强制，但要容忍。
        assert_eq!(解析("注册。"), 指令::注册);
        assert_eq!(解析("注册."), 指令::注册);
        assert_eq!(解析("注册！"), 指令::注册);
        assert_eq!(解析("注册。 "), 指令::注册);
    }

    #[test]
    fn 多余参数目前被忽略() {
        // 零参数指令先忽略尾巴；等有了带参指令再让 解析 返回参数列表。
        assert_eq!(解析("注册 晓"), 指令::注册);
        assert_eq!(解析("注册　全角空格"), 指令::注册);
    }

    #[test]
    fn 前缀不算匹配() {
        // 精确匹配：`注册账号` 不是 `注册`。
        assert_eq!(
            解析("注册账号"),
            指令::未知 {
                原文: "注册账号".to_owned()
            }
        );
    }

    #[test]
    fn 空消息返回未知() {
        assert_eq!(
            解析("   "),
            指令::未知 {
                原文: String::new()
            }
        );
    }
}
