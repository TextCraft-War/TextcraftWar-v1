//! 服务器统一的错误类型：**分层**（D48）+ 错误码 / 玩家文案 / 日志级别三张表。
//!
//! 层次（修正 D43 的单一平坦枚举——传输与业务混在一个枚举里，谁该断连、
//! 谁该 `error` 级全靠人记）：
//!
//! ```text
//! 错误
//! ├── 业务(业务错误)        规则拒绝与服务器业务失败——回一条 error，连接不断
//! │   └── 领域(domain::错误)  `domain` 说"不行"，字段原样带上来
//! ├── 传输(传输错误)        握手、帧、JSON、平台一致性——协议层的事
//! └── 存储(storage::错误)   基础设施失败——唯一的 `error` 级
//! ```
//!
//! 变体分层了，**错误码表仍只有一份**（D43 的教训保留）：它是
//! `docs/arch/protocol.md` 错误码表的镜像。三张表（[`错误::错误码`] /
//! [`错误::玩家文案`] / [`错误::日志级别`]）对三个枚举都是穷尽 `match`——
//! 加失败时编译器逼着每一层一起补。
//!
//! [D43]: ../../../docs/decisions.md
//! [D48]: ../../../docs/decisions.md

use crate::文案;

/// 业务层的失败：玩家的错或规则拒绝。
///
/// **连接不断**：回一条 `error` 继续跑。只有传输层故障才断连。
#[derive(Debug, thiserror::Error)]
pub enum 业务错误 {
    /// `domain` 的规则拒绝。变体字段原样带上来，错误码与玩家文案
    /// 由 [`业务错误`] 的三张表翻译——"拒绝了什么"归领域，"怎么说"归这里。
    #[error(transparent)]
    领域(#[from] domain::错误),

    /// 认不出这条指令。
    #[error("不认识的指令：{指令名}")]
    不认识的指令 {
        /// 插件转发的指令名。
        指令名: String,
    },

    /// 认识指令名，但 `args` 形状不对（D51）：缺参、类型不对，
    /// 或零参指令带了非空 `args`。Koishi 只转发合法调用的指令，
    /// 这条只有插件 bug / 两端偏差才会触发，回 `bad_request`。
    #[error("指令参数形状不对：{指令名}")]
    参数错误 {
        /// 指令名，供日志。
        指令名: String,
    },

    /// 连续多次生成的六位编号都已被占用。
    #[error("连续 {次数} 次生成的编号都已被占用")]
    编号用尽 {
        /// 重试次数。
        次数: u32,
    },
}

/// 传输与协议层的失败：握手、帧、JSON、平台一致性。
#[derive(Debug, thiserror::Error)]
pub enum 传输错误 {
    /// 握手之后又收到一条握手。
    #[error("重复握手")]
    重复握手,

    /// 消息里的平台与连接握手时的平台不一致。
    #[error("消息平台 {消息} 与连接平台 {连接} 不一致")]
    平台不一致 {
        /// 连接握手时的平台编码。
        连接: String,
        /// 消息里带来的平台编码。
        消息: String,
    },

    /// 未知的平台编码。
    #[error("未知平台：{原文}")]
    未知平台 {
        /// 原始字符串，只进日志。
        原文: String,
    },

    /// 等待握手消息超时。
    #[error("握手超时")]
    握手超时,

    /// 连接在握手前被关闭。
    #[error("连接在握手前关闭")]
    连接已关闭,

    /// 底层传输失败。
    #[error("传输失败")]
    传输失败,

    /// 帧不是文本。
    #[error("协议只接受文本帧")]
    非文本帧,

    /// JSON 无法解析。
    #[error("消息格式错误")]
    无法解析,

    /// 第一条消息不是握手。
    #[error("第一条消息必须是 hello")]
    不是握手消息,

    /// 密钥不匹配。
    #[error("令牌错误")]
    令牌错误,

    /// 协议版本不匹配。
    #[error("协议版本不匹配，服务端为 {服务端}")]
    版本不匹配 {
        /// 服务端支持的协议主版本。
        服务端: u32,
    },

    /// 发送失败。
    #[error("发送失败")]
    发送失败,
}

/// 服务器能产生的失败（顶层，D48 分层）。
///
/// 变体只表达"发生了什么"：[`错误::错误码`] 是给 Koishi 的机器可读标签，
/// [`错误::玩家文案`] 是给人看的一句话。**内部错误的原始信息只进日志**，
/// 绝不进这两处。
#[derive(Debug, thiserror::Error)]
pub enum 错误 {
    /// 业务层：规则拒绝或服务器业务失败。
    #[error(transparent)]
    业务(#[from] 业务错误),

    /// 传输层：握手、帧、协议违反。
    #[error(transparent)]
    传输(#[from] 传输错误),

    /// 基础设施层：存储失败。
    #[error(transparent)]
    存储(#[from] storage::错误),
}

impl From<domain::错误> for 错误 {
    fn from(领域错误: domain::错误) -> Self {
        Self::业务(业务错误::领域(领域错误))
    }
}

impl 错误 {
    /// 对外暴露的错误码，取值见 `docs/arch/protocol.md`。
    pub const fn 错误码(&self) -> &'static str {
        match self {
            Self::业务(业务) => 业务.错误码(),
            Self::传输(传输) => 传输.错误码(),
            Self::存储(_) => "internal",
        }
    }

    /// 给玩家看的一句话。
    ///
    /// 内部错误（存储失败、编号用尽）在这里被压成一句"系统开小差了"：
    /// 原始信息进日志，玩家只看到该看到的。
    pub fn 玩家文案(&self) -> String {
        match self {
            Self::业务(业务) => 业务.玩家文案(),
            Self::传输(传输) => 传输.玩家文案(),
            Self::存储(_) => 文案::系统开小差(),
        }
    }

    /// 这条失败该用什么日志级别。
    ///
    /// 跟着"谁的错"走：玩家弄错（不认识的指令、没注册）不该占用 `error`，
    /// 否则真正的故障会被淹掉。分层之后这个判断写在层上——
    /// 传输层全是 `info`，存储层全是 `error`，只有业务层逐变体分。
    pub const fn 日志级别(&self) -> tracing::Level {
        match self {
            Self::业务(业务) => 业务.日志级别(),
            Self::传输(_) => tracing::Level::INFO,
            Self::存储(_) => tracing::Level::ERROR,
        }
    }
}

impl 业务错误 {
    /// 对外暴露的错误码，取值见 `docs/arch/protocol.md`。
    pub const fn 错误码(&self) -> &'static str {
        match self {
            // 码是**对外协议**的词汇，不进 `domain`——那里只表达"拒绝了什么"，
            // 翻成哪个码由这一张表说了算（orphan rule 也不允许给领域类型添方法）。
            Self::领域(领域错误) => match 领域错误 {
                domain::错误::未注册 => "not_registered",
                domain::错误::频道无地区 { .. } => "no_region",
                // 规则拒绝 → bad_request（D49.3 首个落地：冷却中）。
                domain::错误::冷却中 { .. } => "bad_request",
                // 还没有指令路径能产生这两种拒绝。错误码、玩家文案与
                // `docs/arch/protocol.md` 的表三处随产生路径一起定稿（D49.3）；
                // 穷尽 match 是提醒，不是自动完成。
                domain::错误::物资不足 { .. } | domain::错误::数量溢出 { .. } => {
                    "internal"
                },
            },
            Self::不认识的指令 { .. } => "unknown_command",
            Self::参数错误 { .. } => "bad_request",
            Self::编号用尽 { .. } => "internal",
        }
    }

    /// 给玩家看的一句话。
    pub fn 玩家文案(&self) -> String {
        match self {
            Self::领域(领域错误) => match 领域错误 {
                domain::错误::未注册 => 文案::未注册(),
                domain::错误::频道无地区 { .. } => 文案::频道无地区(),
                domain::错误::冷却中 { 剩余秒 } => 文案::冷却中(*剩余秒),
                // 同上：产生路径落地时换成带数值的真文案（D49.3）。
                domain::错误::物资不足 { .. } | domain::错误::数量溢出 { .. } => {
                    文案::系统开小差()
                },
            },
            Self::不认识的指令 { .. } => 文案::不认识的指令(),
            Self::参数错误 { .. } => 文案::消息格式错误(),
            Self::编号用尽 { .. } => 文案::系统开小差(),
        }
    }

    /// 这条失败该用什么日志级别。
    pub const fn 日志级别(&self) -> tracing::Level {
        match self {
            Self::领域(_) => tracing::Level::INFO,
            Self::不认识的指令 { .. } | Self::参数错误 { .. } => tracing::Level::DEBUG,
            Self::编号用尽 { .. } => tracing::Level::ERROR,
        }
    }
}

impl 传输错误 {
    /// 对外暴露的错误码，取值见 `docs/arch/protocol.md`。
    pub const fn 错误码(&self) -> &'static str {
        match self {
            Self::令牌错误 => "forbidden",
            Self::重复握手
            | Self::平台不一致 { .. }
            | Self::未知平台 { .. }
            | Self::握手超时
            | Self::连接已关闭
            | Self::传输失败
            | Self::非文本帧
            | Self::无法解析
            | Self::不是握手消息
            | Self::版本不匹配 { .. }
            | Self::发送失败 => "bad_request",
        }
    }

    /// 给玩家看的一句话。
    pub fn 玩家文案(&self) -> String {
        match self {
            Self::重复握手 => 文案::重复握手(),
            Self::平台不一致 { .. } | Self::未知平台 { .. } | Self::无法解析 => {
                文案::消息格式错误()
            },
            Self::握手超时
            | Self::连接已关闭
            | Self::传输失败
            | Self::非文本帧
            | Self::不是握手消息
            | Self::令牌错误
            | Self::版本不匹配 { .. }
            | Self::发送失败 => 文案::系统开小差(),
        }
    }
}

#[cfg(test)]
mod 测试 {
    use super::{业务错误, 传输错误, 错误};

    /// 顶层的三张表必须对每一层都能答上来——分层不该让任何一层绕过表。
    #[test]
    fn 三个层的码与文案都能产出() {
        let 全部 = [
            错误::业务(业务错误::不认识的指令 {
                指令名: "随便说说".to_owned(),
            }),
            错误::业务(domain::错误::未注册.into()),
            错误::传输(传输错误::重复握手),
            错误::存储(storage::错误::数据损坏 {
                表: "测试",
                列: "测试",
            }),
        ];

        for 每个 in &全部 {
            assert!(!每个.错误码().is_empty(), "错误码为空：{每个:?}");
            assert!(!每个.玩家文案().is_empty(), "玩家文案为空：{每个:?}");
            assert!(!format!("{每个}").is_empty(), "Display 为空：{每个:?}");
        }
    }

    /// 领域拒绝的字段要能原样带到顶层（错误的层级只是包装，不丢信息）。
    #[test]
    fn 领域拒绝保留原始字段() {
        let 失败 = 错误::from(domain::错误::频道无地区 {
            频道_id: "群-1".to_owned(),
        });

        assert_eq!(失败.错误码(), "no_region");
    }
}
