//! 服务器统一的错误类型：错误码 + 给玩家看的一句话。
//!
//! 传输层（握手、帧）与业务层（未注册、频道没地区）**共用一个枚举**，
//! 因为错误码表只能有一份：它是 `docs/protocol.md` 的镜像，
//! 散成两份就一定会漂移（[D43]）。
//!
//! [D43]: ../../../docs/decisions.md

use crate::文案;

/// 服务器能产生的失败。
///
/// 变体只表达"发生了什么"：`错误码` 是给 Koishi 的机器可读标签，
/// `玩家文案` 是给人看的一句话。**内部错误的原始信息只进日志**，
/// 绝不进这两处。
#[derive(Debug, thiserror::Error)]
pub enum 错误 {
    /// 这个平台账号还没注册。
    #[error("玩家尚未注册")]
    未注册,

    /// 当前频道没有绑定地区。
    #[error("频道 {频道_id} 未绑定地区")]
    频道无地区 {
        /// 频道 id，只进日志。
        频道_id: String,
    },

    /// 认不出这条指令。
    #[error("不认识的指令：{原文}")]
    不认识的指令 {
        /// 解析出的第一个词。
        原文: String,
    },

    /// 指令太长，超过协议上限。
    #[error("指令过长：{长度} 字符")]
    文本过长 {
        /// 实际长度（字符数，不是字节数）。
        长度: usize,
    },

    /// 握手之后又收到一条握手。
    #[error("重复握手")]
    重复握手,

    /// 消息里的平台与连接握手时的平台不一致。
    #[error("消息平台 {消息} 与连接平台 {连接} 不一致")]
    平台不一致 {
        /// 连接握手时的平台编码。
        连接: String,
        /// 消息里带来的平台编码。
        消息: String,
    },

    /// 未知的平台编码。
    #[error("未知平台：{原文}")]
    未知平台 {
        /// 原始字符串，只进日志。
        原文: String,
    },

    /// 连续多次生成的六位编号都已被占用。
    #[error("连续 {次数} 次生成的编号都已被占用")]
    编号用尽 {
        /// 重试次数。
        次数: u32,
    },

    /// 存储层失败。
    #[error(transparent)]
    存储(#[from] storage::错误),

    /// 等待握手消息超时。
    #[error("握手超时")]
    握手超时,

    /// 连接在握手前被关闭。
    #[error("连接在握手前关闭")]
    连接已关闭,

    /// 底层传输失败。
    #[error("传输失败")]
    传输失败,

    /// 帧不是文本。
    #[error("协议只接受文本帧")]
    非文本帧,

    /// JSON 无法解析。
    #[error("消息格式错误")]
    无法解析,

    /// 第一条消息不是握手。
    #[error("第一条消息必须是 hello")]
    不是握手消息,

    /// 密钥不匹配。
    #[error("令牌错误")]
    令牌错误,

    /// 协议版本不匹配。
    #[error("协议版本不匹配，服务端为 {服务端}")]
    版本不匹配 {
        /// 服务端支持的协议主版本。
        服务端: u32,
    },

    /// 发送失败。
    #[error("发送失败")]
    发送失败,
}

impl 错误 {
    /// 对外暴露的错误码，取值见 `docs/protocol.md`。
    pub const fn 错误码(&self) -> &'static str {
        match self {
            Self::未注册 => "not_registered",
            Self::频道无地区 { .. } => "no_region",
            Self::不认识的指令 { .. } => "unknown_command",
            Self::文本过长 { .. }
            | Self::重复握手
            | Self::平台不一致 { .. }
            | Self::未知平台 { .. }
            | Self::握手超时
            | Self::连接已关闭
            | Self::传输失败
            | Self::非文本帧
            | Self::无法解析
            | Self::不是握手消息
            | Self::版本不匹配 { .. }
            | Self::发送失败 => "bad_request",
            Self::编号用尽 { .. } | Self::存储(_) => "internal",
            Self::令牌错误 => "forbidden",
        }
    }

    /// 给玩家看的一句话。
    ///
    /// 内部错误（存储失败、编号用尽）在这里被压成一句"系统开小差了"：
    /// 原始信息进日志，玩家只看到该看到的。
    pub fn 玩家文案(&self) -> String {
        match self {
            Self::未注册 => 文案::未注册(),
            Self::频道无地区 { .. } => 文案::频道无地区(),
            Self::不认识的指令 { .. } => 文案::不认识的指令(),
            Self::文本过长 { .. } => 文案::文本过长(),
            Self::重复握手 => 文案::重复握手(),
            Self::平台不一致 { .. } | Self::未知平台 { .. } | Self::无法解析 => {
                文案::消息格式错误()
            },
            Self::编号用尽 { .. }
            | Self::存储(_)
            | Self::握手超时
            | Self::连接已关闭
            | Self::传输失败
            | Self::非文本帧
            | Self::不是握手消息
            | Self::令牌错误
            | Self::版本不匹配 { .. }
            | Self::发送失败 => 文案::系统开小差(),
        }
    }

    /// 这条失败该用什么日志级别。
    ///
    /// 玩家自己弄错的事（不认识的指令、没注册）不该占用 `error`，
    /// 否则真正的故障会被淹掉。
    pub const fn 日志级别(&self) -> tracing::Level {
        match self {
            Self::不认识的指令 { .. } => tracing::Level::DEBUG,
            Self::编号用尽 { .. } | Self::存储(_) => tracing::Level::ERROR,
            Self::未注册
            | Self::频道无地区 { .. }
            | Self::文本过长 { .. }
            | Self::重复握手
            | Self::平台不一致 { .. }
            | Self::未知平台 { .. }
            | Self::握手超时
            | Self::连接已关闭
            | Self::传输失败
            | Self::非文本帧
            | Self::无法解析
            | Self::不是握手消息
            | Self::令牌错误
            | Self::版本不匹配 { .. }
            | Self::发送失败 => tracing::Level::INFO,
        }
    }
}
