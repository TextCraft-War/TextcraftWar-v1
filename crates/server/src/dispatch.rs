//! 指令分发：**路由由 domain 的准入声明驱动**（D49.5），过了身份门再按指令分发。
//!
//! 读写分流（D46）：**写**指令开一个事务（[`处理写`] 统一掌握提交与回滚，
//! 业务以 `AsyncFnOnce` 闭包进来，加写指令不再复制事务样板）；
//! **纯读**路径（身份门、"未知指令的身份判定"）直接在池上借连接查完就还。
//!
//! 时间也从这里注入（D48）：一条消息取一次"到达时刻"，处理器只消费它——
//! 测试要定住时间时，只需要替换这一处的取法。

use domain::实体::时间;
use domain::平台;

use crate::{业务错误, 处理器, 文案, 时钟, 状态, 解析, 错误};

/// 一条来自玩家的指令。
///
/// 平台已经验过（与连接握手一致）；`指令名` 与 `参数` 还没映射成
/// 领域指令——那是 `解析::解析` 的事（D51：过线即结构化，语法归 Koishi）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 来信 {
    /// 消息来自哪个平台。
    pub 平台: 平台,
    /// 群 / 频道 id。游戏只在群里玩。
    pub 频道_id: String,
    /// 平台侧的用户 id。
    pub 用户_uid: String,
    /// Koishi 转发的指令名（游戏词汇，中文）。
    pub 指令名: String,
    /// 指令参数对象，原样过线（D51）；形状的逐指令解释在 `解析`。
    pub 参数: serde_json::Value,
}

/// 处理一条指令，返回给玩家看的文本；怎么塞进协议的消息段是连接层的事。
pub async fn 处理(状态: &状态, 来信: &来信) -> Result<String, 错误> {
    // "这条指令何时到达"在分发层取一次，读写路径共用（D48）。
    let 现在 = 时间(时钟::现在());

    match 解析::解析(&来信.指令名, &来信.参数) {
        解析::结果::指令(指令) => match 指令.准入要求() {
            // 准入声明驱动路由（D49.5）：要什么身份 domain 说了算，
            // 穷尽 match 让新指令不申报就编不过。
            domain::准入要求::免注册 => {
                处理写(状态, async |句柄| {
                    处理器::账号::注册(句柄, 来信, 现在).await
                })
                .await
            },
            domain::准入要求::需注册 => {
                // 身份门（D49）：拦截写在管线上，往后的分支想漏都漏不掉。
                let 绑定 = 查身份(状态, 来信).await?;
                分发已注册(状态, 绑定, 指令, 现在).await
            },
        },
        // 参数错误（D51）与未知指令名一样身份先行：对没注册的人，
        // "参数不对"不重要，"先注册"才重要（impl.md 4.2）。
        解析::结果::参数错误 { 指令名 } => {
            查身份(状态, 来信).await?;

            Err(业务错误::参数错误 { 指令名 }.into())
        },
        解析::结果::不认识 { 指令名 } => {
            查身份(状态, 来信).await?;

            Err(业务错误::不认识的指令 { 指令名 }.into())
        },
    }
}

/// 已通过身份门的指令分发（准入要求 = 需注册 的那些）。这里的
/// [`storage::绑定`] **必然存在**，各分支只管自己的业务，不再各自查身份。
async fn 分发已注册(
    状态: &状态,
    绑定: storage::绑定,
    指令: domain::指令,
    现在: 时间,
) -> Result<String, 错误> {
    match 指令 {
        // 运行时走不到：`注册` 的准入要求是 免注册，在路由层就被接走了。
        // 编译器不知道（穷尽 match 要这一臂），给它与"已注册的人再发注册"
        // 一致的答案（幂等回编号），不用 unreachable。
        domain::指令::注册 => Ok(文案::已经注册(&storage::显示玩家编号(绑定.编号))),
        domain::指令::我的资料 => 处理器::账号::我的资料(&状态.池, 绑定.玩家_id).await,
        domain::指令::签到 => {
            处理写(状态, async |句柄| {
                处理器::经济::签到(句柄, 绑定.玩家_id, 现在).await
            })
            .await
        },
    }
}

/// **身份门**（impl.md 4.3，D49）：每条需注册的指令进路由前都过这里。
///
/// 纯读，池上借连接查完就还，不开事务（D46）；查不到 = 未注册
/// （领域拒绝，D44——结构归 domain，码与文案由错误表翻译）。
async fn 查身份(状态: &状态, 来信: &来信) -> Result<storage::绑定, 错误> {
    storage::查绑定(storage::执行者::池(&状态.池), 来信.平台, &来信.用户_uid)
        .await?
        .ok_or_else(|| domain::错误::未注册.into())
}

/// 写指令的事务壳（D46/D40）：**恰好一个事务**，成功提交、失败回滚。
///
/// 业务以 [`AsyncFnOnce`] 闭包进来，只管拿到 `&mut 事务` 做事；
/// 事务的生死统一在这里——加写指令时提交/回滚样板零复制。
async fn 处理写(
    状态: &状态,
    业务: impl AsyncFnOnce(&mut storage::事务) -> Result<String, 错误>,
) -> Result<String, 错误> {
    let mut 句柄 = storage::开事务(&状态.池).await?;

    match 业务(&mut 句柄).await {
        Ok(文本) => {
            storage::提交(句柄).await?;
            Ok(文本)
        },
        Err(失败) => {
            if let Err(回滚错误) = storage::回滚(句柄).await {
                tracing::warn!(%回滚错误, "回滚失败");
            }
            Err(失败)
        },
    }
}
