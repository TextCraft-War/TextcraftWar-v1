//! 指令分发：**身份门在路由前**，过了门再按指令分发。
//!
//! 读写分流（D46）：**写**指令（如 `注册`）开一个事务，
//! 成功提交、失败回滚；**纯读**指令（身份门、"未知指令的身份判定"）
//! 直接在池上借连接查完就还——不给读占 BEGIN/COMMIT 的连接租期。
//! 将来某条读指令要写库了，它的处理函数自己改收 `&mut 事务`，
//! 分发层的形态不变。
//!
//! 时间也从这里注入（D48）：处理器收 `时间` 参数，不自己取"现在"——
//! 测试要定住时间时，只需要替换这一处的取法。

use domain::实体::时间;
use domain::平台;

use crate::{业务错误, 处理器, 文案, 时钟, 状态, 解析, 错误};

/// 一条来自玩家的指令。
///
/// 平台已经验过（与连接握手一致），文本还没解析——解析是 `解析::解析` 的事。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 来信 {
    /// 消息来自哪个平台。
    pub 平台: 平台,
    /// 群 / 频道 id。游戏只在群里玩。
    pub 频道_id: String,
    /// 平台侧的用户 id。
    pub 用户_uid: String,
    /// 玩家原话，未解析。
    pub 文本: String,
}

/// 处理一条指令，返回给玩家看的文本；怎么塞进协议的消息段是连接层的事。
pub async fn 处理(状态: &状态, 来信: &来信) -> Result<String, 错误> {
    match 解析::解析(&来信.文本) {
        // 唯一走在身份门之前的指令：没注册的人才需要它（幂等建号，D41）。
        解析::结果::指令(domain::指令::注册) => 处理注册(状态, 来信).await,
        // 身份门（D49）：其余一切指令都先过它，再进各自的分支——
        // 拦截写在管线上，往后的分支**想漏都漏不掉**。
        解析::结果::指令(指令) => {
            let 绑定 = 查身份(状态, 来信).await?;
            分发已注册(状态, 绑定, 指令).await
        },
        解析::结果::不认识 { 原文 } => {
            // 身份先行：查不到人就是"未注册"，而不是"不认识的指令"——
            // 对没注册的人，"你发的是什么"不重要，"先注册"才重要（impl.md 4.2）。
            查身份(状态, 来信).await?;

            Err(业务错误::不认识的指令 { 原文 }.into())
        },
    }
}

/// 已通过身份门的指令分发。这里的 [`storage::绑定`] **必然存在**，
/// 各分支只管自己的业务，不再各自查身份。
async fn 分发已注册(
    状态: &状态,
    绑定: storage::绑定,
    指令: domain::指令,
) -> Result<String, 错误> {
    match 指令 {
        // 运行时走不到：`注册` 在身份门之前就被外层接走了。编译器不知道，
        // 给它与"已注册的人再发注册"一致的答案（幂等回编号），不用 unreachable。
        domain::指令::注册 => Ok(文案::已经注册(&storage::显示玩家编号(绑定.编号))),
        domain::指令::我的资料 => 处理器::账号::我的资料(&状态.池, 绑定.玩家_id).await,
    }
}

/// **身份门**（impl.md 4.3，D49）：除 `注册` 外每条指令进路由前都过这里。
///
/// 纯读，池上借连接查完就还，不开事务（D46）；查不到 = 未注册
/// （领域拒绝，D44——结构归 domain，码与文案由错误表翻译）。
async fn 查身份(状态: &状态, 来信: &来信) -> Result<storage::绑定, 错误> {
    storage::查绑定(storage::执行者::池(&状态.池), 来信.平台, &来信.用户_uid)
        .await?
        .ok_or_else(|| domain::错误::未注册.into())
}

/// `注册` 的写路径：**恰好一个事务**，成功提交、失败回滚（D40/D41）。
async fn 处理注册(状态: &状态, 来信: &来信) -> Result<String, 错误> {
    // 时间在开事务之前取：它表示"这条指令何时到达"，不依赖数据库。
    let 现在 = 时间(时钟::现在());

    let mut 句柄 = storage::开事务(&状态.池).await?;
    let 结果 = 处理器::账号::注册(&mut 句柄, 来信, 现在).await;

    match 结果 {
        Ok(文案) => {
            storage::提交(句柄).await?;
            Ok(文案)
        },
        Err(失败) => {
            if let Err(回滚错误) = storage::回滚(句柄).await {
                tracing::warn!(%回滚错误, "回滚失败");
            }
            Err(失败)
        },
    }
}
