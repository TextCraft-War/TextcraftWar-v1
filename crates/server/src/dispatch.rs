//! 指令分发：**身份先行**，再按指令名路由。
//!
//! 读写分流（D46）：**写**指令（如 `注册`）开一个事务，
//! 成功提交、失败回滚；**纯读**指令（现在只有"未知指令的身份判定"）
//! 直接在池上借连接查完就还——不给读占 BEGIN/COMMIT 的连接租期。
//! 将来某条读指令要写库了，它的处理函数自己改收 `&mut 事务`，
//! 分发层的形态不变。

use domain::平台;

use crate::{
    命令::{self, 指令},
    状态, 账号, 错误,
};

/// 一条来自玩家的指令。
///
/// 平台已经验过（与连接握手一致），文本还没解析——解析是 [`命令::解析`] 的事。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 来信 {
    /// 消息来自哪个平台。
    pub 平台: 平台,
    /// 群 / 频道 id。游戏只在群里玩。
    pub 频道_id: String,
    /// 平台侧的用户 id。
    pub 用户_uid: String,
    /// 玩家原话，未解析。
    pub 文本: String,
}

/// 处理一条指令，返回给玩家看的文本；怎么塞进协议的消息段是连接层的事。
pub async fn 处理(状态: &状态, 来信: &来信) -> Result<String, 错误> {
    match 命令::解析(&来信.文本) {
        指令::注册 => 处理注册(状态, 来信).await,
        指令::未知 { 原文 } => {
            // 身份先行：查不到人就是"未注册"，而不是"不认识的指令"。
            // 纯读，池上直查，不开事务（D46）。
            let 绑定 =
                storage::查绑定(storage::执行者::池(&状态.池), 来信.平台, &来信.用户_uid).await?;

            if 绑定.is_none() {
                return Err(错误::未注册);
            }

            Err(错误::不认识的指令 { 原文 })
        },
    }
}

/// `注册` 的写路径：**恰好一个事务**，成功提交、失败回滚（D40/D41）。
async fn 处理注册(状态: &状态, 来信: &来信) -> Result<String, 错误> {
    let mut 句柄 = storage::开事务(&状态.池).await?;
    let 结果 = 账号::注册(&mut 句柄, 来信).await;

    match 结果 {
        Ok(文案) => {
            storage::提交(句柄).await?;
            Ok(文案)
        },
        Err(失败) => {
            if let Err(回滚错误) = storage::回滚(句柄).await {
                tracing::warn!(%回滚错误, "回滚失败");
            }
            Err(失败)
        },
    }
}
