//! 指令分发：**身份先行**，再按指令名路由。
//!
//! 每条指令的形状固定成三拍：
//!
//! ```text
//! 开一个事务
//!   → 分派（注册要写库，其它指令第一件事是查"你是谁"）
//!   → 成功提交 / 失败回滚
//! ```
//!
//! 为什么纯读指令也开事务：只有一条事务路径，就没有"读走池、写走事务"的分叉，
//! 也不会出现"某个读指令以后要写，签名得全改"（[D40]）。
//!
//! [D40]: ../../../docs/decisions.md

use domain::平台;

use crate::{
    命令::{self, 指令},
    状态, 账号, 错误,
};

/// 一条来自玩家的指令。
///
/// 平台已经验过（与连接握手一致），文本还没解析——解析是 [`命令::解析`] 的事。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 来信 {
    /// 消息来自哪个平台。
    pub 平台: 平台,
    /// 群 / 频道 id。游戏只在群里玩。
    pub 频道_id: String,
    /// 平台侧的用户 id。
    pub 用户_uid: String,
    /// 玩家原话，未解析。
    pub 文本: String,
}

/// 处理一条指令：**恰好一个事务**，成功提交、失败回滚。
///
/// 返回的是给玩家看的文本；怎么塞进协议的消息段是连接层的事。
pub async fn 处理(状态: &状态, 来信: &来信) -> Result<String, 错误> {
    let 本条 = 命令::解析(&来信.文本);

    let mut 事务 = storage::开事务(&状态.池).await?;
    let 结果 = 分派(&mut 事务, &本条, 来信).await;

    match 结果 {
        Ok(文案) => {
            storage::提交(事务).await?;
            Ok(文案)
        },
        Err(失败) => {
            if let Err(回滚错误) = storage::回滚(事务).await {
                tracing::warn!(%回滚错误, "回滚失败");
            }
            Err(失败)
        },
    }
}

/// 按指令名路由。
///
/// 未注册的人除了 `注册`（它自己会处理"已注册"）以外，发什么都只得到
/// "先注册"——**不自动注册**是跨平台绑定能成立的前提（D23）。
async fn 分派(
    事务: &mut storage::事务, 本条: &指令, 来信: &来信
) -> Result<String, 错误> {
    match 本条 {
        指令::注册 => 账号::注册(事务, 来信).await,
        指令::未知 { 原文 } => {
            // 身份先行：查不到人就是"未注册"，而不是"不认识的指令"。
            if storage::查绑定(事务, 来信.平台, &来信.用户_uid)
                .await?
                .is_none()
            {
                return Err(错误::未注册);
            }

            Err(错误::不认识的指令 {
                原文: 原文.clone()
            })
        },
    }
}
