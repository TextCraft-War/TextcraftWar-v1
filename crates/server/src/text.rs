//! 玩家可见文本的**唯一出口**。
//!
//! 规则（见 `crates/server/docs/impl.md` 第七节）：
//!
//! - 任何要发给玩家的字符串都由这里产生，业务代码里不许出现字面量；
//! - 排版：标题 `====[标题]====`，字段前缀 `■`，数值一律走 [`千分位`]；
//! - 函数收结构化数据、返回 `String`，将来接多语言只换本模块的实现。

use domain::实体::{库存 as 库存实体, 玩家 as 玩家实体};

/// 整数千分位：`1500000` → `1,500,000`；负数保留负号，逗号只进数字部分。
pub(crate) fn 千分位(值: i64) -> String {
    let 符号 = if 值 < 0 { "-" } else { "" };
    let 数字 = 值.unsigned_abs().to_string();
    let 位数 = 数字.len();
    let 逗号数 = 位数.saturating_sub(1) / 3;

    let mut 结果 = String::with_capacity(位数.saturating_add(逗号数));
    for (序号, 字符) in 数字.chars().enumerate() {
        if 序号 > 0 && 位数.saturating_sub(序号) % 3 == 0 {
            结果.push(',');
        }
        结果.push(字符);
    }

    format!("{符号}{结果}")
}

/// 注册成功。
pub(crate) fn 注册成功(编号: &str, 地区: &str) -> String {
    format!("====[注册完成]====\n■ 编号：{编号}\n■ 出生地区：{地区}")
}

/// `签到` 成功，报本次所得。
pub(crate) fn 签到成功(获得: i64) -> String {
    format!("====[签到成功]====\n■ 生活资料 +{}", 千分位(获得))
}

/// `我的资料`：一段能直接发进群里的完整状态。
///
/// 字段取舍（S3）：只放玩家**现在就能对它做点什么**的状态——人口、稳定度、
/// 工资、科技、生产次数、位置、联军、背包；时间锚点（签到/炮击冷却）等
/// 各自的指令落地时再进这份资料，避免展示一堆玩家无从着手的数。
/// 物品按 `物品` 的词表顺序（资源 → 装备 → 弹药）排列，来自 `BTreeMap` 的序。
pub(crate) fn 我的资料(
    编号: &str,
    玩家: &玩家实体,
    库存: &库存实体,
    驻扎地区: Option<&str>,
    联军: Option<&str>,
) -> String {
    let mut 行: Vec<String> = Vec::new();
    行.push("====[我的资料]====".to_owned());
    行.push(format!("■ 编号：{编号}"));
    行.push(format!(
        "■ 人口：{}（工人 {} / 私军 {} / 地下工人 {} / 休假工人 {}）",
        千分位(玩家.总人口()),
        千分位(玩家.工人),
        千分位(玩家.私军),
        千分位(玩家.地下工人),
        千分位(玩家.休假工人),
    ));
    行.push(format!(
        "■ 稳定度：{}　工资：{}　科技：{}　生产次数：{}",
        千分位(玩家.稳定度),
        千分位(玩家.工资),
        千分位(玩家.科技),
        千分位(i64::from(玩家.生产次数)),
    ));
    行.push(驻扎地区.map_or_else(
        || "■ 驻扎地区：无".to_owned(),
        |名| format!("■ 驻扎地区：{名}"),
    ));
    行.push(联军.map_or_else(|| "■ 联军：未加入".to_owned(), |名| format!("■ 联军：{名}")));

    if 库存.0.is_empty() {
        行.push("■ 库存：（空）".to_owned());
    } else {
        let 条目: Vec<String> = 库存
            .0
            .iter()
            .map(|(品, 数量)| format!("{} {}", 品.名称(), 千分位(*数量)))
            .collect();
        行.push(format!("■ 库存：{}", 条目.join("　")));
    }

    行.join("\n")
}

/// 这个账号已经注册过了。
