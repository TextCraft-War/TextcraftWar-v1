//! 玩家可见文本的**唯一出口**。
//!
//! 规则（见 `crates/server/docs/design.md` 第七节）：
//!
//! - 任何要发给玩家的字符串都由这里产生，业务代码里不许出现字面量；
//! - 排版：标题 `====[标题]====`，字段前缀 `■`，数值千分位；
//! - 函数收结构化数据、返回 `String`，将来接多语言只换本模块的实现。

/// 注册成功。
pub(crate) fn 注册成功(编号: &str, 地区: &str) -> String {
    format!("====[注册完成]====\n■ 编号：{编号}\n■ 出生地区：{地区}")
}

/// 这个账号已经注册过了。
pub(crate) fn 已经注册(编号: &str) -> String {
    format!("====[已经注册过]====\n■ 编号：{编号}\n■ 不用再注册，直接发指令就行")
}

/// 玩家还没注册。
pub(crate) fn 未注册() -> String {
    "■ 你还不是指挥官。\n■ 先发【注册】创建角色".to_owned()
}

/// 当前频道没有绑定地区。
pub(crate) fn 频道无地区() -> String {
    "■ 当前频道还没有绑定地区，注册暂时不可用".to_owned()
}

/// 不认识的指令。
pub(crate) fn 不认识的指令() -> String {
    "■ 不认识的指令".to_owned()
}

/// 指令太长。
pub(crate) fn 文本过长() -> String {
    "■ 指令太长了，请分几条发".to_owned()
}

/// 已经握过手了。
pub(crate) fn 重复握手() -> String {
    "■ 已经握过手了".to_owned()
}

/// 消息本身不合法（平台不对、JSON 坏了）。
pub(crate) fn 消息格式错误() -> String {
    "■ 消息格式错误".to_owned()
}

/// 内部错误的统一说法。原始信息只进日志。
pub(crate) fn 系统开小差() -> String {
    "■ 系统开小差了，稍后再试".to_owned()
}

#[cfg(test)]
mod 测试 {
    use super::{已经注册, 注册成功};

    #[test]
    fn 注册文案带标题与两个字段() {
        let 文案 = 注册成功("P123456", "新伊甸");

        assert!(文案.starts_with("====[注册完成]====\n"), "实际：{文案}");
        assert!(文案.contains("■ 编号：P123456"), "实际：{文案}");
        assert!(文案.contains("■ 出生地区：新伊甸"), "实际：{文案}");
    }

    #[test]
    fn 重复注册要说清已经注册过() {
        let 文案 = 已经注册("P123456");

        assert!(文案.contains("已经注册过"), "实际：{文案}");
        assert!(文案.contains("P123456"), "实际：{文案}");
    }
}
