//! 把玩家原话解析成 [`domain::指令`]。
//!
//! 规则（v1，见 `crates/server/docs/impl.md` 4.1）：
//!
//! 1. 按空白切词（[`词元游标`]，零分配）；**句末标点**只在句尾的词上剥
//!    （兼容原版 `签到。` 的习惯，但不强制），纯标点的尾巴不算参数；
//! 2. 第一个词是指令名（词头），**精确匹配**，不做前缀匹配
//!    （否则 `生产` 和 `生产次数` 会打架）；
//! 3. 零参指令**多余参数默认拒绝**（D49.1，回 `bad_request`）；
//!    `注册` 豁免——Koishi 侧可能在指令后带尾巴。
//!
//! 解析只认词，不碰数据库、不判权限：`注册` 能不能成功是下一层的事。
//! **产出是 `domain::指令`**（D44/D48）：一条指令"意味着什么动作"是规则层的事；
//! 认不出的词头留在本层，由分发层结合身份决定对外错误码
//! （`not_registered` / `unknown_command`）。

/// 解析结果：认识的进领域，认不出的留在本层。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum 结果 {
    /// 认识的领域指令。
    指令(domain::指令),
    /// 认识词头，但它不收参数而玩家带了多余参数（D49.1）。
    多参数 {
        /// 认出来的词头，供错误提示。
        词头: String,
    },
    /// 认不出（保留词头那个词，供日志与提示）。
    不认识 {
        /// 指令名那个词；空消息时是空串。
        原文: String,
    },
}

/// 句末允许被剥掉的标点。
const 句末标点: [char; 4] = ['。', '.', '！', '!'];

/// 零分配词元游标：按空白逐词借出 `&str`，不收集 `Vec`（D49.1）。
///
/// 带参指令（S4 起）在这里逐个取**位置参数**，取完用 [`词元游标::有实义剩余`]
/// 断言没有多余尾巴——多余参数不静默吞。
pub(crate) struct 词元游标<'a> {
    词元: std::iter::Peekable<std::str::SplitWhitespace<'a>>,
}

impl<'a> 词元游标<'a> {
    /// 从玩家原话出发建游标（首尾空白自动跳过）。
    // 每次解析都是新建即用，`Default` 给不出有意义的空游标。
    #[allow(
        clippy::new_without_default,
        reason = "无意义的空游标不值得一个 Default"
    )]
    pub(crate) fn 新(原文: &'a str) -> Self {
        Self {
            词元: 原文.split_whitespace().peekable(),
        }
    }

    /// 借出下一个词元。
    pub(crate) fn 下一个(&mut self) -> Option<&'a str> {
        self.词元.next()
    }

    /// 后面还有没有词元（不消费）。
    pub(crate) fn 还有下一个(&mut self) -> bool {
        self.词元.peek().is_some()
    }

    /// 后面还有没有**实义**参数：把句末标点剥掉之后不空的词元才算
    /// （`签到。` 的句号、`签到 ..` 的省略点都不算参数）。
    pub(crate) fn 有实义剩余(&mut self) -> bool {
        self.词元
            .any(|词| !词.trim_end_matches(句末标点).is_empty())
    }
}

/// 词头 → 指令。加指令只改这张表（D49：词头映射必变，主干冻结）。
fn 识别(词头: &str) -> Option<domain::指令> {
    match 词头 {
        "注册" => Some(domain::指令::注册),
        "我的资料" => Some(domain::指令::我的资料),
        "签到" => Some(domain::指令::签到),
        _ => None,
    }
}

/// 解析一条玩家原话。
pub(crate) fn 解析(原文: &str) -> 结果 {
    let mut 游标 = 词元游标::新(原文);
    let Some(词头) = 游标.下一个() else {
        return 结果::不认识 {
            原文: String::new(),
        };
    };

    // 词头是最后一个词时才是"句尾"：句末标点只在那时剥。
    // `签到。` 是签到；`签到。 晓` 的词头带着句号，照旧不认识（与拆词规则一致）。
    let 词头 = if 游标.还有下一个() {
        词头
    } else {
        词头.trim_end_matches(句末标点)
    };

    let Some(指令) = 识别(词头) else {
        return 结果::不认识 {
            原文: 词头.to_owned(),
        };
    };

    // 多余参数默认拒绝（D49.1）；注册 豁免（Koishi 侧可能带尾巴）。
    if 指令 != domain::指令::注册 && 游标.有实义剩余() {
        return 结果::多参数 {
            词头: 词头.to_owned(),
        };
    }

    结果::指令(指令)
}

#[cfg(test)]
mod 测试 {
    use super::{结果, 解析, 词元游标};
    use domain::指令;

    #[test]
    fn 注册能被认出来() {
        assert_eq!(解析("注册"), 结果::指令(指令::注册));
    }

    #[test]
    fn 我的资料能被认出来() {
        assert_eq!(解析("我的资料"), 结果::指令(指令::我的资料));
        assert_eq!(解析("我的资料。"), 结果::指令(指令::我的资料));
    }

    #[test]
    fn 签到能被认出来_句末标点不碍事() {
        assert_eq!(解析("签到"), 结果::指令(指令::签到));
        assert_eq!(解析("签到。"), 结果::指令(指令::签到));
        assert_eq!(解析("签到！"), 结果::指令(指令::签到));
        assert_eq!(
            解析("签到 .."),
            结果::指令(指令::签到),
            "纯标点的尾巴不算参数"
        );
    }

    #[test]
    fn 我的资料_前缀与拆词都不算匹配() {
        // 精确匹配：拆开两个字、带尾巴，都不是 `我的资料`。
        assert_eq!(
            解析("我的 资料"),
            结果::不认识 {
                原文: "我的".to_owned()
            }
        );
        assert_eq!(
            解析("我的资料夹"),
            结果::不认识 {
                原文: "我的资料夹".to_owned()
            }
        );
    }

    #[test]
    fn 首尾空白与换行不影响识别() {
        assert_eq!(解析("  注册  "), 结果::指令(指令::注册));
        assert_eq!(解析("\n注册\n"), 结果::指令(指令::注册));
    }

    #[test]
    fn 多余参数默认拒绝_注册豁免() {
        // D49.1：零参指令不再静默吞尾巴，只放行 `注册`（Koishi 侧可能带尾巴）。
        assert_eq!(
            解析("签到 晓"),
            结果::多参数 {
                词头: "签到".to_owned()
            }
        );
        assert_eq!(
            解析("我的资料 啊"),
            结果::多参数 {
                词头: "我的资料".to_owned()
            }
        );
        assert_eq!(解析("注册 晓"), 结果::指令(指令::注册));
        assert_eq!(解析("注册　全角空格"), 结果::指令(指令::注册));
    }

    #[test]
    fn 词头不在句尾时不剥标点() {
        // `签到。 晓` 的词头带着句号：它不是句尾，照旧不认识。
        assert_eq!(
            解析("签到。 晓"),
            结果::不认识 {
                原文: "签到。".to_owned()
            }
        );
    }

    #[test]
    fn 前缀不算匹配() {
        // 精确匹配：`注册账号` 不是 `注册`。
        assert_eq!(
            解析("注册账号"),
            结果::不认识 {
                原文: "注册账号".to_owned()
            }
        );
    }

    #[test]
    fn 空消息返回不认识() {
        assert_eq!(
            解析("   "),
            结果::不认识 {
                原文: String::new()
            }
        );
    }

    #[test]
    fn 游标逐词借出不收集() {
        let mut 游标 = 词元游标::新("  签到　尾巴1 尾巴2。 ");

        assert_eq!(游标.下一个(), Some("签到"));
        assert!(游标.还有下一个());
        assert_eq!(游标.下一个(), Some("尾巴1"));
        assert!(游标.还有下一个());
        assert_eq!(游标.下一个(), Some("尾巴2。"));
        assert!(!游标.还有下一个());
        // 有实义剩余 是消费性检查，放最后：纯句末标点的尾巴不算参数。
        assert!(!游标.有实义剩余());
    }

    #[test]
    fn 有实义剩余_分得清实义参数与纯标点尾巴() {
        let mut 有参数 = 词元游标::新("签到 晓");
        assert_eq!(有参数.下一个(), Some("签到"));
        assert!(有参数.有实义剩余(), "晓 是实义参数");

        let mut 只有句号 = 词元游标::新("签到 。");
        assert_eq!(只有句号.下一个(), Some("签到"));
        assert!(!只有句号.有实义剩余());
    }
}
