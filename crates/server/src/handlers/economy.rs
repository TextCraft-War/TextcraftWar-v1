//! 经济类指令：`签到`、招募工人、设置工资、生产（S4 逐条落地）。
//!
//! 写路径形状与 [`crate::处理器::账号`] 一致：事务句柄 + 注入的时间 →
//! 玩家文案；事务的生死由 `crate::分发::处理写` 统一掌握。

use domain::实体::{时间, 物品, 玩家 as 玩家实体, 玩家Id, 资源};

use crate::{文案, 错误};

/// `签到`：每天一次、奖励固定（data-model 4.1），S4 的首条冷却类指令。
///
/// 流程：事务内读玩家行 → [`玩家实体::签到`] 判冷却 → **谓词条件更新**
/// 抢签到锚点（storage impl.md 2.4：并发的第二次签到在数据库层面被拦下）→
/// 给库存加奖励。四步在**同一个事务**里：锚点与奖励同生共死，
/// 回滚时不会出现"领了奖没打卡"或"打了卡没领奖"。
pub(crate) async fn 签到(
    句柄: &mut storage::事务,
    玩家_id: 玩家Id,
    现在: 时间,
) -> Result<String, 错误> {
    let 玩家 = storage::查玩家(storage::执行者::事务(句柄), 玩家_id)
        .await?
        .ok_or(storage::错误::数据损坏 {
            表: "平台绑定",
            列: "玩家_id",
        })?;

    let 获得 = 玩家实体::签到(玩家.上次签到, 现在)?;

    if !storage::签到打卡(句柄, 玩家_id, 现在).await? {
        // 规则判定与条件更新之间，另一个并发签到刚提交。结果确定：
        // 赢家把锚点推到了"刚刚"，本分支按整段冷却拒绝，不必重读重算。
        return Err(domain::错误::冷却中 {
            剩余秒: 玩家实体::签到冷却秒,
        }
        .into());
    }

    storage::增库存(
        句柄,
        storage::库存所有者::玩家(玩家_id),
        物品::资源(资源::生活资料),
        获得,
    )
    .await?;

    // 不记编号（D30）：`P…` 是秘密凭证，日志只出现内部主键。
    tracing::info!(玩家_id = 玩家_id.0, 获得, "签到");

    Ok(文案::签到成功(获得))
}
