//! 账号类指令。
//!
//! 现在只有 `注册` 与 `我的资料`；`绑定账户` 这些会一条条加进来。
//! 写路径的形状：**事务句柄 + 已解析的来信 + 注入的时间 → 玩家文案**，
//! 不自己 `commit`——事务的生死由 `crate::分发::处理` 统一掌握。
//! 纯读路径（`我的资料`）不收事务，收 [`storage::执行者`]（D46）。

use domain::实体::{时间, 玩家Id, 玩家Uid};
use rand::Rng as _;

use crate::{业务错误, 文案, 来信, 错误};

/// `注册`：建玩家 + 第一条平台绑定，出生地区 = 注册所在频道所属地区（D41）。
///
/// 顺序是有意义的：
///
/// 1. **先串行化**（D42）——同一个平台账号的两次注册不会各建一个玩家；
/// 2. **再查绑定**——已经注册过就回编号，直接结束（幂等，不报错）；
/// 3. **再查地区**——频道没绑地区就回 `no_region`，不建一个"无家可归"的玩家；
/// 4. 建玩家（撞号重试）→ 写绑定。
///
/// 三步读都传 [`storage::执行者::事务`]：注册事务里的读必须走同一条连接——
/// 串行化锁与"再查绑定"的分身术不成立，串行化就白做了（D42/D46）。
pub(crate) async fn 注册(
    句柄: &mut storage::事务,
    来信: &来信,
    现在: 时间,
) -> Result<String, 错误> {
    storage::串行化注册(句柄, 来信.平台, &来信.用户_uid).await?;

    if let Some(绑定) =
        storage::查绑定(storage::执行者::事务(句柄), 来信.平台, &来信.用户_uid).await?
    {
        // 重复注册不报错：协议层不做去重，靠业务幂等（protocol.md 第四节）。
        return Ok(文案::已经注册(&storage::显示玩家编号(绑定.编号)));
    }

    let 地区 = storage::查频道地区(storage::执行者::事务(句柄), 来信.平台, &来信.频道_id)
        .await?
        .ok_or_else(|| domain::错误::频道无地区 {
            频道_id: 来信.频道_id.clone(),
        })?;

    let (玩家_id, 编号) = 建玩家(句柄, 地区.id.0, 现在).await?;

    storage::插入绑定(句柄, 玩家_id, 来信.平台, &来信.用户_uid, 现在).await?;

    // 不记编号：`P…` 是秘密凭证，日志里出现它就等于把它泄出去（D30）。
    tracing::info!(玩家_id = 玩家_id.0, 地区 = %地区.名称, "新玩家注册");

    Ok(文案::注册成功(
        &storage::显示玩家编号(编号),
        &地区.名称,
    ))
}

/// `我的资料`：查自己的全部状态（纯读，D46——不占事务的连接租期）。
///
/// 四次读每次都从 [`storage::连接池`] 借一条连接、查完即还（[`storage::执行者::池`]）：
/// 玩家详情、背包、驻扎地区名、联军名。两处 `None` 都按数据损坏处理：
/// 玩家的外键指向不存在的行只可能是坏数据（绑定→玩家由 FK 保证；
/// 地区不可删除，design.md 2.3），宁可报错也不装作"一切正常"。
pub(crate) async fn 我的资料(
    池: &storage::连接池, 玩家_id: 玩家Id
) -> Result<String, 错误> {
    let 玩家 = storage::查玩家(storage::执行者::池(池), 玩家_id)
        .await?
        .ok_or(storage::错误::数据损坏 {
            表: "平台绑定",
            列: "玩家_id",
        })?;

    let 库存 = storage::查库存(storage::执行者::池(池), storage::库存所有者::玩家(玩家_id)).await?;

    let 驻扎地区 = match 玩家.驻扎地区 {
        Some(地区_id) => Some(
            storage::查地区名称(storage::执行者::池(池), 地区_id)
                .await?
                .ok_or(storage::错误::数据损坏 {
                    表: "玩家",
                    列: "驻扎地区_id",
                })?,
        ),
        None => None,
    };

    let 联军 = match 玩家.联军 {
        Some(联军_id) => Some(
            storage::查联军名称(storage::执行者::池(池), 联军_id)
                .await?
                .ok_or(storage::错误::数据损坏 {
                    表: "玩家",
                    列: "联军_id",
                })?,
        ),
        None => None,
    };

    // 自己的编号回显给自己是唯一允许出现 `P…` 的输出（D30：别人的编号不进任何输出）。
    tracing::debug!(玩家_id = 玩家_id.0, "查我的资料");

    Ok(文案::我的资料(
        &storage::显示玩家编号(玩家.uid),
        &玩家,
        &库存,
        驻扎地区.as_deref(),
        联军.as_deref(),
    ))
}

/// 建一个玩家，撞号就换一个编号重试。
///
/// **规则与策略的分界**（D44）：合法区间与重试上限在 [`domain::编号`]，
/// 是规则；候选编号怎么抽出来是服务器策略——`rand` 的区间抽样自带
/// 无偏与终止保证，`domain` 在零依赖下重造只会引入偏差与死循环风险。
async fn 建玩家(
    句柄: &mut storage::事务,
    驻扎地区_id: i64,
    创建时间: 时间,
) -> Result<(玩家Id, 玩家Uid), 错误> {
    for _ in 0..domain::编号::重试上限 {
        let 编号 = 随机编号();

        if let Some(玩家_id) = storage::插入玩家(句柄, 编号, 驻扎地区_id, 创建时间).await?
        {
            return Ok((玩家_id, 编号));
        }

        tracing::warn!("六位编号撞号，换一个重试");
    }

    Err(业务错误::编号用尽 {
        次数: domain::编号::重试上限,
    }
    .into())
}

/// 随机抽一个候选编号，落在 `domain::编号` 的合法区间内。
fn 随机编号() -> 玩家Uid {
    玩家Uid(rand::rng().random_range(domain::编号::最小..=domain::编号::最大))
}

#[cfg(test)]
mod 测试 {
    use super::随机编号;
    use domain::编号::{合法, 最大, 最小};

    #[test]
    fn 随机编号落在六位区间里() {
        for _ in 0..1_000 {
            let 编号 = 随机编号();
            assert!(
                合法(编号.0) && (最小..=最大).contains(&编号.0),
                "越界：{}",
                编号.0
            );
        }
    }

    #[test]
    fn 编号带_p_前缀显示() {
        use domain::实体::玩家Uid;
        assert_eq!(storage::显示玩家编号(玩家Uid(123_456)), "P123456");
    }
}
