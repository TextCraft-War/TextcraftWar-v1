//! 玩家可见文本的**唯一出口**。
//!
//! 规则（见 `crates/server/docs/impl.md` 第七节）：
//!
//! - 任何要发给玩家的字符串都由这里产生，业务代码里不许出现字面量；
//! - 排版：标题 `====[标题]====`，字段前缀 `■`，数值一律走 `千分位`；
//! - 函数收结构化数据、返回 `String`，将来接多语言只换本模块的实现。
//!
//! 按指令域分文件（D50）：`账号` / `经济` 各管各的文案，协议与系统的
//! 固定提示语归 `错误文案`，排版辅助归 `格式`（`千分位` 只在模块树内用）。
//! 本文件只做汇总 re-export——调用方一律走 `文案::函数` 根路径，
//! 域内再怎么拆都看不见。

#[path = "format.rs"]
mod 格式;
#[path = "economy.rs"]
mod 经济;
#[path = "account.rs"]
mod 账号;
#[path = "errors.rs"]
mod 错误文案;

pub(crate) use 经济::签到成功;
pub(crate) use 账号::{已经注册, 我的资料, 注册成功};
pub(crate) use 错误文案::{
    不认识的指令, 冷却中, 多余参数, 文本过长, 未注册, 消息格式错误, 系统开小差, 重复握手,
    频道无地区,
};
