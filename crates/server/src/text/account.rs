//! 账号类文案：`注册` / `我的资料`。
//!
//! **只有注册会回显 `P…` 编号**（[`注册成功`] / [`已经注册`]）——那是玩家
//! 拿到自己凭证的唯一入口；别人的编号永远不作为参数进文案。

use domain::实体::{库存 as 库存实体, 玩家 as 玩家实体};

use super::格式::千分位;

/// 注册成功。
pub(crate) fn 注册成功(编号: &str, 地区: &str) -> String {
    format!("====[注册完成]====\n■ 编号：{编号}\n■ 出生地区：{地区}")
}

/// 这个账号已经注册过了。
pub(crate) fn 已经注册(编号: &str) -> String {
    format!("====[已经注册过]====\n■ 编号：{编号}\n■ 不用再注册，直接发指令就行")
}

/// `我的资料`：一段能直接发进群里的完整状态。
///
/// 字段取舍（S3）：只放玩家**现在就能对它做点什么**的状态——人口、稳定度、
/// 工资、科技、生产次数、位置、联军、背包；时间锚点（签到/炮击冷却）等
/// 各自的指令落地时再进这份资料，避免展示一堆玩家无从着手的数。
/// 物品按 `物品` 的词表顺序（资源 → 装备 → 弹药）排列，来自 `BTreeMap` 的序。
pub(crate) fn 我的资料(
    编号: &str,
    玩家: &玩家实体,
    库存: &库存实体,
    驻扎地区: Option<&str>,
    联军: Option<&str>,
) -> String {
    let mut 行: Vec<String> = Vec::new();
    行.push("====[我的资料]====".to_owned());
    行.push(format!("■ 编号：{编号}"));
    行.push(format!(
        "■ 人口：{}（工人 {} / 私军 {} / 地下工人 {} / 休假工人 {}）",
        千分位(玩家.总人口()),
        千分位(玩家.工人),
        千分位(玩家.私军),
        千分位(玩家.地下工人),
        千分位(玩家.休假工人),
    ));
    行.push(format!(
        "■ 稳定度：{}　工资：{}　科技：{}　生产次数：{}",
        千分位(玩家.稳定度),
        千分位(玩家.工资),
        千分位(玩家.科技),
        千分位(i64::from(玩家.生产次数)),
    ));
    行.push(驻扎地区.map_or_else(
        || "■ 驻扎地区：无".to_owned(),
        |名| format!("■ 驻扎地区：{名}"),
    ));
    行.push(联军.map_or_else(|| "■ 联军：未加入".to_owned(), |名| format!("■ 联军：{名}")));

    if 库存.0.is_empty() {
        行.push("■ 库存：（空）".to_owned());
    } else {
        let 条目: Vec<String> = 库存
            .0
            .iter()
            .map(|(品, 数量)| format!("{} {}", 品.名称(), 千分位(*数量)))
            .collect();
        行.push(format!("■ 库存：{}", 条目.join("　")));
    }

    行.join("\n")
}

#[cfg(test)]
mod 测试 {
    use std::collections::BTreeMap;

    use super::{已经注册, 我的资料, 注册成功};
    use domain::实体::{库存, 玩家, 资源};
    use domain::实体::{时间, 物品};

    #[test]
    fn 注册文案带标题与两个字段() {
        let 文案 = 注册成功("P123456", "新伊甸");

        assert!(文案.starts_with("====[注册完成]====\n"), "实际：{文案}");
        assert!(文案.contains("■ 编号：P123456"), "实际：{文案}");
        assert!(文案.contains("■ 出生地区：新伊甸"), "实际：{文案}");
    }

    #[test]
    fn 重复注册要说清已经注册过() {
        let 文案 = 已经注册("P123456");

        assert!(文案.contains("已经注册过"), "实际：{文案}");
        assert!(文案.contains("P123456"), "实际：{文案}");
    }

    /// 一个"刚注册、两手空空"的玩家：人口 0、无联军、背包空。
    fn 空玩家() -> 玩家 {
        玩家 {
            id: domain::实体::玩家Id(1),
            uid: domain::实体::玩家Uid(123_456),
            工人: 0,
            私军: 0,
            地下工人: 0,
            休假工人: 0,
            科技: 1,
            生产技术: 1,
            厂房: 0,
            地下工厂投入: 0,
            科技池投入: 0,
            科技池容量: 1_000,
            生产次数: 0,
            军事行动点: 0,
            稳定度: 100,
            工资: 0,
            上次签到: None,
            今日招募数量: 0,
            上次炮击: None,
            上次驻扎: None,
            驻扎地区: None,
            联军: None,
            联军职务: None,
            联军权限等级: None,
            联军贡献: 0,
            加入联军时间: None,
            出生保护至: Some(时间(1_800_000_000)),
        }
    }

    #[test]
    fn 资料文案_空背包与未加入联军() {
        let 文案 = 我的资料("P123456", &空玩家(), &库存(BTreeMap::new()), None, None);

        assert!(文案.starts_with("====[我的资料]====\n"), "实际：{文案}");
        assert!(文案.contains("■ 编号：P123456"), "实际：{文案}");
        assert!(
            文案.contains("■ 人口：0（工人 0 / 私军 0 / 地下工人 0 / 休假工人 0）"),
            "实际：{文案}"
        );
        assert!(文案.contains("■ 稳定度：100"), "实际：{文案}");
        assert!(文案.contains("■ 驻扎地区：无"), "实际：{文案}");
        assert!(文案.contains("■ 联军：未加入"), "实际：{文案}");
        assert!(文案.contains("■ 库存：（空）"), "实际：{文案}");
    }

    #[test]
    fn 资料文案_背包带物品名与千分位() {
        let mut 袋 = 库存(BTreeMap::new());
        袋.增(物品::资源(资源::生活资料), 1_500_000)
            .expect("增生活资料");
        袋.增(物品::资源(资源::钢铁), 200).expect("增钢铁");

        let 文案 = 我的资料("P123456", &空玩家(), &袋, Some("新伊甸"), None);

        assert!(
            文案.contains("■ 库存：生活资料 1,500,000　钢铁 200"),
            "实际：{文案}"
        );
        assert!(文案.contains("■ 驻扎地区：新伊甸"), "实际：{文案}");
        // 稳定度允许为负：负号要在千分位之外，分组在数字部分。
        let 带负 = 玩家 {
            稳定度: -12_345,
            ..空玩家()
        };
        assert!(
            我的资料("P1", &带负, &库存(BTreeMap::new()), None, None).contains("■ 稳定度：-12,345"),
            "实际：{文案}"
        );
    }
}
