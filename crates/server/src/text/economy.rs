//! 经济类文案：`签到` 等（S4 起逐条落地，一域一文件，D50）。

use super::格式::千分位;

/// `签到` 成功，报本次所得。
pub(crate) fn 签到成功(获得: i64) -> String {
    format!("====[签到成功]====\n■ 生活资料 +{}", 千分位(获得))
}

#[cfg(test)]
mod 测试 {
    use super::签到成功;

    #[test]
    fn 签到文案带标题与千分位所得() {
        let 文案 = 签到成功(1_200);

        assert!(文案.starts_with("====[签到成功]====\n"), "实际：{文案}");
        assert!(文案.contains("■ 生活资料 +1,200"), "实际：{文案}");
    }
}
