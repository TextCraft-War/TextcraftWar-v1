//! 账号类指令。
//!
//! 现在只有 `注册`；`我的资料` / `绑定账户` 这些会一条条加进来。
//! 每个函数都遵循同一形状：**输入事务 + 已解析的来信，输出一段给玩家看的文本**，
//! 不自己 `commit`——事务的生死由 [`crate::分发::处理`] 统一掌握。

use rand::Rng as _;

use crate::{文案, 时钟, 来信, 错误};

/// 编号撞号后的重试次数。
///
/// 90 万个号、2 人规模，撞一次就已经很不巧了；8 次全撞是"编号空间被占满"，
/// 那时候该扩容而不是继续重试。
const 编号重试次数: u32 = 8;

/// `注册`：建玩家 + 第一条平台绑定，出生地区 = 注册所在频道所属地区（[D41]）。
///
/// 顺序是有意义的：
///
/// 1. **先串行化**（[D42]）——同一个平台账号的两次注册不会各建一个玩家；
/// 2. **再查绑定**——已经注册过就回编号，直接结束（幂等，不报错）；
/// 3. **再查地区**——频道没绑地区就回 `no_region`，不建一个"无家可归"的玩家；
/// 4. 建玩家（撞号重试）→ 写绑定。
///
/// [D41]: ../../../docs/decisions.md
/// [D42]: ../../../docs/decisions.md
pub(crate) async fn 注册(
    事务: &mut storage::事务, 来信: &来信
) -> Result<String, 错误> {
    storage::串行化注册(事务, 来信.平台, &来信.用户_uid).await?;

    if let Some(绑定) = storage::查绑定(事务, 来信.平台, &来信.用户_uid).await? {
        // 重复注册不报错：协议层不做去重，靠业务幂等（protocol.md 第四节）。
        return Ok(文案::已经注册(&显示编号(绑定.编号)));
    }

    let 地区 = storage::查频道地区(事务, 来信.平台, &来信.频道_id)
        .await?
        .ok_or_else(|| 错误::频道无地区 {
            频道_id: 来信.频道_id.clone(),
        })?;

    let 时间 = 时钟::现在();
    let (玩家_id, 编号) = 建玩家(事务, 地区.id, 时间).await?;

    storage::插入绑定(事务, 玩家_id, 来信.平台, &来信.用户_uid, 时间).await?;

    // 不记编号：`P…` 是秘密凭证，日志里出现它就等于把它泄出去（D30）。
    tracing::info!(玩家_id, 地区 = %地区.名称, "新玩家注册");

    Ok(文案::注册成功(&显示编号(编号), &地区.名称))
}

/// 建一个玩家，撞号就换一个编号重试。
///
/// 编号在这里生成（而不是 `storage` 里）：**生成策略是服务器的事**，
/// 存储层只回答"这个号被占了吗"，这样撞号路径在测试里才构造得出来。
async fn 建玩家(
    事务: &mut storage::事务,
    驻扎地区_id: i64,
    时间: i64,
) -> Result<(i64, i32), 错误> {
    for _ in 0..编号重试次数 {
        let 编号 = 随机编号();

        if let Some(玩家_id) = storage::插入玩家(事务, 编号, 驻扎地区_id, 时间).await?
        {
            return Ok((玩家_id, 编号));
        }

        tracing::warn!("六位编号撞号，换一个重试");
    }

    Err(错误::编号用尽 {
        次数: 编号重试次数
    })
}

/// 随机生成一个六位编号，范围与 DB 的 DOMAIN `六位编号` 一致。
fn 随机编号() -> i32 {
    rand::rng().random_range(domain::编号::最小..=domain::编号::最大)
}

/// 把编号显示成 `P123456`。
fn 显示编号(编号: i32) -> String {
    domain::编号::显示(domain::编号::玩家前缀, 编号)
}

#[cfg(test)]
mod 测试 {
    use super::{显示编号, 随机编号};

    #[test]
    fn 随机编号落在六位区间里() {
        for _ in 0..1_000 {
            let 编号 = 随机编号();
            assert!(
                (domain::编号::最小..=domain::编号::最大).contains(&编号),
                "越界：{编号}"
            );
        }
    }

    #[test]
    fn 编号带_p_前缀显示() {
        assert_eq!(显示编号(123_456), "P123456");
    }
}
