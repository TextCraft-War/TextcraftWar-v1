//! 六位编号：玩家 `P…`、地区 `R…`、联军 `C…`。
//!
//! 三者都是 6 位随机数字，落库只存数字（DOMAIN `六位编号`），
//! 前缀只在展示与解析时出现。数字空间**互相独立**：`P123456`、`R123456`、
//! `C123456` 可以同时存在，所以解析必须先看前缀。
//!
//! 保密级别不同（[D30] / [D36]）：`P` 与 `R` 是秘密凭证，
//! 不得进日志、不得出现在公开输出里；`C` 是公开门牌，可以随便展示。
//!
//! [D30]: ../../../docs/decisions.md
//! [D36]: ../../../docs/decisions.md

/// 玩家编号前缀。**秘密**：知道 `P123456` 才能在别的群找到这个人。
pub const 玩家前缀: char = 'P';

/// 地区编号前缀。**秘密**：知道 `R123456` 才打得到这个地区。
pub const 地区前缀: char = 'R';

/// 联军编号前缀。**公开**：不授予任何权限，排行榜里也能出现。
pub const 联军前缀: char = 'C';

/// 编号的下界（含）。与 DB 的 DOMAIN `六位编号` 一致。
pub const 最小: i32 = 100_000;

/// 编号的上界（含）。与 DB 的 DOMAIN `六位编号` 一致。
pub const 最大: i32 = 999_999;

/// 把数字显示成带前缀的编号，如 `P123456`。
///
/// 不做补零：数据库的 CHECK 保证取值落在 `100_000..=999_999`，
/// 真出现 `P42` 说明数据已经坏了，**让它看起来坏了**比自动补齐更好排查。
pub fn 显示(前缀: char, 编号: i32) -> String {
    format!("{前缀}{编号}")
}

#[cfg(test)]
mod 测试 {
    use super::{地区前缀, 显示, 最大, 最小, 玩家前缀, 联军前缀};

    #[test]
    fn 三个前缀都能拼出来() {
        assert_eq!(显示(玩家前缀, 123_456), "P123456");
        assert_eq!(显示(地区前缀, 123_456), "R123456");
        assert_eq!(显示(联军前缀, 123_456), "C123456");
    }

    #[test]
    fn 边界值仍是六位() {
        assert_eq!(显示(玩家前缀, 最小), "P100000");
        assert_eq!(显示(玩家前缀, 最大), "P999999");
    }
}
