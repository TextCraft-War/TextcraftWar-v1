//! 纯游戏规则层：签到、工业生产、战争结算的**纯粹计算**。
//!
//! # 硬约束
//!
//! 本 crate **零外部依赖、零 IO、零 async**。所有规则写成
//! `fn 结算(旧状态, 指令) -> (新状态, 事件)` 形式的纯函数，
//! 因此只靠 `cargo test` 就能验证，不需要 PostgreSQL，也不需要 WebSocket。
//! 连错误类型都手写 `Display`——`thiserror` 也不进这里。
//!
//! # 模块
//!
//! - [`编号`]：六位编号的区间、前缀、显示与重试上限（规则，D44）
//! - [`实体`]：`玩家` / `联军` / `地区` / `库存` / `物品` 词表等，data-model 第五节的落地
//! - [`命令`]：领域指令词汇表（路由 `match` 它，不 match 字符串）
//! - `错误`（`错误类型` 模块）：领域规则拒绝，与传输 / 存储错误解耦
//!
//! # 依赖方向（由编译器强制，不是靠自觉）
//!
//! ```text
//! server -> { domain, storage, protocol }
//! storage -> domain
//! protocol -> serde（不含 domain）
//! domain -> 无
//! ```
//!
//! 这条分层带来的直接好处：战争结算可以「纯函数批量算完，再一次性写库」，
//! 而不是「边算边锁行」——性能红线从架构上就被满足了，不靠自律。

// rustc 拒绝非 ASCII 模块**文件名**（error[E0754]），
// 所以文件用英文，模块名保持中文，靠 `#[path]` 转一层。
//
// 模块名不与要导出的类型重名（E0255：模块与类型在同一个命名空间）：
// `错误类型` 里是 `错误`，`命令` 里是 `指令`。
#[path = "command.rs"]
pub mod 命令;
#[path = "model.rs"]
pub mod 实体;
#[path = "uid.rs"]
pub mod 编号;
#[path = "error.rs"]
mod 错误类型;

pub use 错误类型::错误;
// 平台从 `实体` 提到根上：`storage` / `server` 都按 `domain::平台` 用它。
pub use 实体::平台;
