//! 领域规则拒绝：`domain` 层说"不行"的唯一方式。
//!
//! 只表达**游戏规则**拒绝了什么，不关心传输、不关心数据库——
//! 那两类失败分别在 `server` 与 `storage` 的错误类型里，三者在 `server`
//! 组装协议错误码时才相遇。
//!
//! `domain` **零依赖**，所以这里不用 `thiserror`，`Display` / `Error` 手写。
//! 文本只面向日志（开发者），玩家看到的说法由 `server` 的 `文案` 模块另出。

use std::fmt;

/// 规则拒绝。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 错误 {
    /// 这个平台账号还没有玩家：除 `注册` 外的一切指令都过不去（D23）。
    未注册,

    /// 当前频道没有绑定地区：注册定不了出生地区，别的指令也定位不了"你在哪"（D41）。
    频道无地区 {
        /// 频道 id，只进日志。
        频道_id: String,
    },

    /// 库存扣减时不够扣（[`crate::实体::库存::增`] 的不变量拒绝）。
    物资不足 {
        /// 哪种物品。
        物品: crate::实体::物品,
        /// 想扣多少。
        需要: i64,
        /// 实际有多少。
        现有: i64,
    },

    /// 库存加法溢出（i64 上界）。正常玩法碰不到；碰到说明输入已坏，宁可拒绝不可静默饱和。
    数量溢出 {
        /// 哪种物品。
        物品: crate::实体::物品,
    },

    /// 动作还在冷却（`签到` 的一天一次、将来的炮击间隔……）。
    ///
    /// 距上次执行还差的秒数一并带回——它只进日志与提示，"怎么说"归 `server`。
    冷却中 {
        /// 还要等多少秒。
        剩余秒: i64,
    },
}

impl fmt::Display for 错误 {
    fn fmt(&self, 格式: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::未注册 => 格式.write_str("玩家尚未注册"),
            Self::频道无地区 { 频道_id } => write!(格式, "频道 {频道_id} 未绑定地区"),
            Self::物资不足 {
                物品, 需要, 现有
            } => write!(格式, "物资 {物品} 不足：需要 {需要}，现有 {现有}"),
            Self::数量溢出 { 物品 } => write!(格式, "物资 {物品} 的数量溢出"),
            Self::冷却中 { 剩余秒 } => write!(格式, "冷却中：还需 {剩余秒} 秒"),
        }
    }
}

impl std::error::Error for 错误 {}

#[cfg(test)]
mod 测试 {
    use super::错误;
    use crate::实体::{物品, 资源};

    #[test]
    fn 每个变体都能打印() {
        let 全部 = [
            错误::未注册,
            错误::频道无地区 {
                频道_id: "群-1".to_owned(),
            },
            错误::物资不足 {
                物品: 物品::资源(资源::生活资料),
                需要: 500,
                现有: 300,
            },
            错误::数量溢出 {
                物品: 物品::资源(资源::钢铁),
            },
            错误::冷却中 { 剩余秒: 86_400 },
        ];

        for 每个 in &全部 {
            assert!(!format!("{每个}").is_empty(), "打印为空：{每个:?}");
        }
    }
}
