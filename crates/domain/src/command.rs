//! 领域指令：服务器认识的动作词汇表。
//!
//! 路由 `match` 的是这个枚举，**不是字符串**——"玩家原话"与"服务器动作"的
//! 分界线画在这里：文本怎么清洗、怎么切词是 `server` 解析器的事；
//! 一条指令**意味着什么动作**，是规则层的事。
//!
//! 带参指令（如 `招募工人 <数量>`）在这里给变体挂**强类型**字段，
//! 参数的合法性校验也落在构造/解析侧，不让裸字符串流进规则函数。

/// 一条已识别的玩家指令。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 指令 {
    /// `注册`：建玩家 + 首条平台绑定（D41）。
    注册,
    /// `我的资料`：查自己的全部状态（纯读，S3）。
    我的资料,
}
