//! 领域指令：服务器认识的动作词汇表。
//!
//! 路由 `match` 的是这个枚举，**不是字符串**——"玩家原话"与"服务器动作"的
//! 分界线画在这里：文本怎么清洗、怎么切词是 `server` 解析器的事；
//! 一条指令**意味着什么动作**，是规则层的事。
//!
//! 带参指令（如 `招募工人 <数量>`）在这里给变体挂**强类型**字段，
//! 参数的合法性校验也落在构造/解析侧，不让裸字符串流进规则函数。

/// 一条已识别的玩家指令。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 指令 {
    /// `注册`：建玩家 + 首条平台绑定（D41）。
    注册,
    /// `我的资料`：查自己的全部状态（纯读，S3）。
    我的资料,
    /// `签到`：每天一次的固定奖励（S4，首条冷却类指令）。
    签到,
}

/// 每条指令的**准入要求**（D49.5）：身份与冷却要求的申报表。
///
/// "权限属于 domain"的兑现——加指令不在 [`指令::准入要求`] 里申报，
/// 编译不过；"怎么核验"（读绑定、读玩家行、加锁）是 IO，归 `server` /
/// `storage`，这里只声明"要什么"。核验通过后产出**私有构造的凭据**作为
/// 规则函数的必填参数（防漏检与并发重入），凭据随 S6/S7 的跨实体指令引入。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 准入要求 {
    /// 身份门之前放行：`注册` 是身份的起点，没有玩家也执行（D41）。
    免注册,
    /// 需要已注册的玩家：分发前查绑定，查不到按"未注册"拒绝。
    需注册,
}

impl 指令 {
    /// 这条指令的准入要求。分发层照声明路由——加指令变体而不申报，编译失败。
    pub const fn 准入要求(&self) -> 准入要求 {
        match self {
            Self::注册 => 准入要求::免注册,
            Self::我的资料 | Self::签到 => 准入要求::需注册,
        }
    }
}
